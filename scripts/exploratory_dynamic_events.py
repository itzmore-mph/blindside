"""Exploratory: ``p_blind_side`` against SkillCorner's possession labels and defending phases.

Not pre-registered. docs/PREREGISTRATION.md and the primary comparison of
docs/INCREMENTAL.md are not touched and not rerun. For the included engagements of the two
pose matches the script tabulates

- four columns of the pressed possession per pre-registered bin of ``p_blind_side``, under
  both bounds of the angular uncertainty, and
- the share of engagements each blind-side label calls blind per defending phase of
  ``phases_of_play.csv``, with Cohen's kappa of the XY proxy against the pose label.

Run from the repository root:
``uv run python scripts/exploratory_dynamic_events.py --write-docs``.
Needs the body pose and the tracking of the two pose matches, as ``blindside reproduce`` does.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from blindside.analysis.baseline import N_BOOTSTRAP, cluster_bootstrap_weights
from blindside.analysis.dynamic_events import (
    EPV_DELTA,
    GRADED_COLUMNS,
    LABEL_THRESHOLD,
    PHASE_COLUMN,
    context_by_bin,
    defending_phase,
    phase_agreement,
    possession_context,
)
from blindside.analysis.incremental import MIN_BIN_SIZE
from blindside.analysis.pipeline import attach_pose, inclusion_flow, load_test_table
from blindside.features.pose_features import BOUNDS, FOV_HALF_ANGLE_DEG, pose_feature_table

DOC = Path("docs/EXPLORATORY_DYNAMIC_EVENTS.md")
MARKER_START = (
    "<!-- exploratory:start (generated by scripts/exploratory_dynamic_events.py, "
    "do not edit by hand) -->"
)
MARKER_END = "<!-- exploratory:end -->"
BLIND_FEATURES = ("p_blind_side_head", "p_blind_side_torso")
#: Column, tabulated column, what it shows, scale and digits.
MEASURES: tuple[tuple[str, str, str, float, int], ...] = (
    (EPV_DELTA, EPV_DELTA, "mean", 1.0, 4),
    *(
        (name, f"{name}_hard", "share graded `hard` or `very_hard`, %", 100.0, 1)
        for name in GRADED_COLUMNS
    ),
)


def _md_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def _cell(value: float, low: float, high: float, scale: float, digits: int, sign: str = "") -> str:
    if np.isnan(value):
        return ""
    text = f"{scale * value:{sign}.{digits}f}"
    if np.isnan(low):
        return text
    return f"{text} ({scale * low:{sign}.{digits}f} to {scale * high:{sign}.{digits}f})"


def render(
    test: pd.DataFrame,
    features: dict[str, pd.DataFrame],
    context: pd.DataFrame,
    phase: np.ndarray,
    weights: np.ndarray,
) -> str:
    """The generated block of docs/EXPLORATORY_DYNAMIC_EVENTS.md."""
    lines: list[str] = []
    add = lines.append

    add("### 2.1 Sample and coverage\n")
    add(
        f"{len(test):,} included on-ball engagements in {test['cluster'].nunique():,} pressed "
        f"possessions, the test set of docs/INCREMENTAL.md section 1.2. Each possession column is "
        "read from the `player_possession` row that the engagement points to "
        "(`associated_player_possession_event_id`). Engagements of one possession share its "
        "values, which the cluster bootstrap accounts for.\n"
    )
    coverage = pd.DataFrame(
        {
            "Column": [f"`{name}`" for name, *_ in MEASURES],
            "Engagements with a value": [
                f"{int(context[name].notna().sum()):,}" for name, *_ in MEASURES
            ],
            "Share, %": [f"{100 * context[name].notna().mean():.1f}" for name, *_ in MEASURES],
            "Tabulated as": [what for _, _, what, *_ in MEASURES],
            "Overall": [
                f"{scale * np.nanmean(context[column]):.{digits}f}"
                for _, column, _, scale, digits in MEASURES
            ],
        }
    )
    add(_md_table(coverage))
    add("")

    add("### 2.2 Possession columns by bin of `p_blind_side`\n")
    add(
        "Bins as fixed in docs/PREREGISTRATION.md section 11. Intervals: cluster bootstrap over "
        f"possessions, {N_BOOTSTRAP:,} resamples, stratified by match, percentile 95%. Bins below "
        f"{MIN_BIN_SIZE} engagements carry no interval. Each cell also gives the engagements "
        "with a value.\n"
    )
    contrasts = []
    for name, column, what, scale, digits in MEASURES:
        values = context[column].to_numpy(dtype=float)
        add(f"`{name}`, {what}:\n")
        rows = []
        for feature in BLIND_FEATURES:
            for bound in BOUNDS:
                p = features[bound][feature].to_numpy(dtype=float)
                table, contrast = context_by_bin(p, values, weights)
                row = {"Feature": f"`{feature}`", "Bound": bound}
                for _, r in table.iterrows():
                    row[f"{r['bin']}"] = (
                        f"{_cell(r['rate'], r['rate_low'], r['rate_high'], scale, digits)}"
                        f", n = {int(r['n']):,}"
                    )
                rows.append(row)
                contrasts.append(
                    {
                        "Column": f"`{name}`",
                        "Feature": f"`{feature}`",
                        "Bound": bound,
                        "Blind minus in view (95% interval), EPV or points": (
                            _cell(*contrast, scale, digits, "+")
                        ),
                        "Interval excludes zero": (
                            ""
                            if np.isnan(contrast[1])
                            else "yes"
                            if contrast[1] > 0 or contrast[2] < 0
                            else "no"
                        ),
                    }
                )
        add(_md_table(pd.DataFrame(rows)))
        add("")
    add("Blind bin minus in-view bin, all columns:\n")
    contrast_frame = pd.DataFrame(contrasts)
    add(_md_table(contrast_frame))
    excluded = int((contrast_frame["Interval excludes zero"] == "yes").sum())
    add("")
    add(
        f"{excluded} of {len(contrast_frame)} intervals exclude zero. They are not independent: "
        "the two bounds and the two body segments describe almost the same engagements. No "
        "correction for multiple comparisons is applied, because no claim is tested here.\n"
    )

    add("### 2.3 Defending phases\n")
    event_phase = test[PHASE_COLUMN].astype(object).to_numpy()
    same = int((event_phase == phase).sum())
    add(
        f"Defending phase of the pressing team: `{PHASE_COLUMN}` of the row of "
        "`phases_of_play.csv` whose frame range holds the engagement start "
        "(`frame_start <= t0 < frame_end`). "
        f"{int((phase == 'outside every phase').sum()):,} engagements start between two phases. "
        f"The engagement row of the dynamic events carries a column of the same name. It gives "
        f"the same phase for {same:,} of {len(test):,} engagements ({100 * same / len(test):.1f}%)"
        ". Why the two differ for the rest was not investigated. The pre-registered baseline "
        "uses the column of the engagement row and is not affected.\n"
    )
    add(
        f"Pose label: `p_blind_side` above {LABEL_THRESHOLD:g}, lower bound (the upper bound "
        "changes the shares by at most a few tenths of a point, docs/INCREMENTAL.md section 1.10). "
        f"XY proxy: presser more than {FOV_HALF_ANGLE_DEG:g} degrees off the carrier's direction "
        f"of travel. Kappa: Cohen's kappa of the proxy against the pose label, cluster bootstrap "
        f"95% interval, none below {MIN_BIN_SIZE} engagements. No outcome column is used.\n"
    )
    agreement = phase_agreement(test, features, phase, weights)
    shown = pd.DataFrame(
        {
            "Defending phase": [f"`{g}`" if g != "all" else "all" for g in agreement["group"]],
            "Engagements": agreement["n"].map("{:,}".format),
            "Pose blind, head, %": (100 * agreement["pose_blind"]).map("{:.1f}".format),
            "Pose blind, torso, %": (100 * agreement["torso_blind"]).map("{:.1f}".format),
            "Proxy blind, %": (100 * agreement["xy_blind"]).map("{:.1f}".format),
            "Kappa, head (95% interval)": [
                _cell(r["kappa"], r["kappa_low"], r["kappa_high"], 1.0, 2, "+")
                for _, r in agreement.iterrows()
            ],
            "Kappa, torso (95% interval)": [
                _cell(r["kappa_torso"], r["kappa_torso_low"], r["kappa_torso_high"], 1.0, 2, "+")
                for _, r in agreement.iterrows()
            ],
        }
    )
    add(_md_table(shown))
    add("")
    speed = test["carrier_speed"].to_numpy(dtype=float)
    medians = pd.Series(speed).groupby(phase).median()
    add(
        "Median carrier speed per phase in m/s, for reading the kappa column: "
        + ", ".join(f"`{g}` {medians[g]:.1f}" for g in agreement["group"] if g in medians.index)
        + "."
    )
    return "\n".join(lines)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/EXPLORATORY_DYNAMIC_EVENTS.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help=f"update {DOC.as_posix()}")
    args = parser.parse_args(argv)

    test, _ = inclusion_flow(load_test_table(), with_pose=True)
    test, poses = attach_pose(test)
    features = {bound: pose_feature_table(test, poses, bound=bound) for bound in BOUNDS}
    weights = cluster_bootstrap_weights(
        test["cluster"].to_numpy(), test["match_id"].to_numpy(), N_BOOTSTRAP, seed=0
    )
    markdown = render(test, features, possession_context(test), defending_phase(test), weights)
    print(markdown)
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
