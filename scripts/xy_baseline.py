"""Phase 3: fit the XY baseline on the matches without body pose and score it on the pose matches.

Follows docs/PREREGISTRATION.md sections 3, 5 and 7 to 9. The baseline is tuned and fitted on
the 18 matches without pose, frozen, and evaluated on the included engagements of the two pose
matches. No pose feature is computed here. The orientation tables are read for their keys
only, to apply inclusion criterion 1.

Run from the repository root: ``uv run python scripts/xy_baseline.py --write-docs``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

from blindside.analysis.baseline import (
    N_BOOTSTRAP,
    TUNING_FOLDS,
    bootstrap_metrics,
    cluster_bootstrap_weights,
    leave_one_match_out,
    logit,
    predict_probability,
    tune_and_fit,
)
from blindside.analysis.pipeline import inclusion_flow, load_tables
from blindside.data.paths import cache_dir
from blindside.features.engagements import POSSESSION_LABELS, PRIMARY_OUTCOME
from blindside.features.xy_baseline import (
    CATEGORICAL_FEATURES,
    NUMERIC_FEATURES,
)

DOC = Path("docs/BASELINE.md")
MARKER_START = "<!-- baseline:start (generated by scripts/xy_baseline.py, do not edit by hand) -->"
MARKER_END = "<!-- baseline:end -->"
MINIMUM_EVENTS = 100
NO_LABELS = tuple(name for name in CATEGORICAL_FEATURES if name not in POSSESSION_LABELS)
METRIC_LABELS = {"log_loss": "Log loss", "auc": "ROC AUC", "brier": "Brier score"}


def _md_table(frame: pd.DataFrame, decimals: dict[str, int] | None = None, default: int = 3) -> str:
    decimals = decimals or {}
    out = frame.copy()
    for column in out.columns:
        if pd.api.types.is_integer_dtype(out[column]):
            out[column] = out[column].map(lambda v: f"{v:,}")
        elif pd.api.types.is_float_dtype(out[column]):
            digits = decimals.get(column, default)
            out[column] = out[column].map(lambda v, d=digits: f"{v:.{d}f}")
    header = "| " + " | ".join(out.columns) + " |"
    rule = "|" + "---|" * len(out.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in out.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def calibration(y: np.ndarray, p: np.ndarray) -> tuple[float, float]:
    """Intercept and slope of a logistic regression of the outcome on the predicted logit."""
    model = LogisticRegression(C=1e6, max_iter=1000).fit(logit(p).reshape(-1, 1), y.astype(int))
    return float(model.intercept_[0]), float(model.coef_[0, 0])


def coefficient_table(model, top: int = 12) -> pd.DataFrame:
    """Largest coefficients of the fitted pipeline, on standardised and one-hot features."""
    names = model.named_steps["features"].get_feature_names_out()
    coefficients = model.named_steps["model"].coef_[0]
    order = np.argsort(-np.abs(coefficients))[:top]
    return pd.DataFrame(
        {
            "Feature": [names[i].split("__", 1)[1] for i in order],
            "Coefficient": coefficients[order],
            "Odds ratio": np.exp(coefficients[order]),
        }
    )


def _metric_rows(result: pd.DataFrame, names: dict[str, str]) -> pd.DataFrame:
    rows = []
    for model, label in names.items():
        for metric, metric_label in METRIC_LABELS.items():
            row = result[(result["model"] == model) & (result["metric"] == metric)].iloc[0]
            entry = {
                "Model": label,
                "Metric": metric_label,
                "Estimate": f"{row['estimate']:.4f}",
                "95% interval": f"{row['ci_low']:.4f} to {row['ci_high']:.4f}",
                "Difference to constant": "",
                "95% interval of the difference": "",
            }
            versus = result[
                (result["model"] == model) & (result["metric"] == f"{metric}_vs_constant")
            ]
            if len(versus) and metric != "auc":
                d = versus.iloc[0]
                entry["Difference to constant"] = f"{d['estimate']:+.4f}"
                entry["95% interval of the difference"] = (
                    f"{d['ci_low']:+.4f} to {d['ci_high']:+.4f}"
                )
            rows.append(entry)
    return pd.DataFrame(rows)


def render(
    train_flow: pd.DataFrame,
    test_flow: pd.DataFrame,
    train: pd.DataFrame,
    test: pd.DataFrame,
    tuning: pd.DataFrame,
    result: pd.DataFrame,
    per_match: pd.DataFrame,
    lomo: pd.DataFrame,
    coefficients: pd.DataFrame,
    calibration_values: tuple[float, float],
) -> str:
    """Markdown of the generated block of docs/BASELINE.md."""
    lines: list[str] = []
    add = lines.append
    y_train, y_test = train[PRIMARY_OUTCOME], test[PRIMARY_OUTCOME]

    add("### 1.1 Sources and definitions\n")
    add(
        "- Design: docs/PREREGISTRATION.md sections 3, 5 and 7 to 9. All numbers in this block are "
        "produced by `scripts/xy_baseline.py`."
    )
    add(
        "- Primary outcome: possession loss of the pressed possession "
        "(`associated_player_possession_end_type == possession_loss`)."
    )
    add(
        f"- Features: {len(NUMERIC_FEATURES)} numeric and {len(CATEGORICAL_FEATURES)} categorical "
        "XY features (`blindside.features.xy_baseline.BASELINE_FEATURES`). No pose feature."
    )
    add(
        "- Model: L2 logistic regression, `C` chosen by grouped "
        f"{TUNING_FOLDS}-fold cross-validation over the training matches, then frozen."
    )
    add(
        f"- Intervals: cluster bootstrap over pressed possessions, {N_BOOTSTRAP:,} resamples, "
        "stratified by match, percentile 95%. Differences are paired.\n"
    )

    add("### 1.2 Inclusion\n")
    add("Training matches (18 without body pose):\n")
    add(_md_table(train_flow))
    add("\nTest matches (1925299 and 1996435):\n")
    add(_md_table(test_flow))
    events = int(y_test.sum())
    add(
        f"\nPrimary outcome events: {int(y_train.sum()):,} of {len(train):,} in training "
        f"({100 * y_train.mean():.1f}%), {events:,} of {len(test):,} in the test set "
        f"({100 * y_test.mean():.1f}%). The pre-registered minimum of {MINIMUM_EVENTS} events is "
        f"{'met' if events >= MINIMUM_EVENTS else 'NOT met'}.\n"
    )
    by_match = (
        test.groupby("match_id")
        .agg(
            Engagements=(PRIMARY_OUTCOME, "size"),
            Possessions=("cluster", "nunique"),
            Events=(PRIMARY_OUTCOME, "sum"),
            rate=(PRIMARY_OUTCOME, "mean"),
        )
        .reset_index()
    )
    by_match["Events"] = by_match["Events"].astype(int)
    by_match["rate"] *= 100
    by_match.columns = ["Match", "Engagements", "Possessions", "Events", "Rate, %"]
    add(_md_table(by_match.astype({"Match": str}), {"Rate, %": 1}))
    add("")

    add("### 1.3 Penalty tuning on the training matches\n")
    shown = tuning.copy()
    shown["chosen"] = shown["chosen"].map({True: "yes", False: ""})
    shown.columns = ["C", "Cross-validated log loss", "SD over folds", "Chosen"]
    add(_md_table(shown, {"C": 4, "Cross-validated log loss": 4, "SD over folds": 4}))
    add("")

    add("### 1.4 Out-of-sample performance on the pose matches\n")
    add(
        _md_table(
            _metric_rows(
                result,
                {
                    "constant": "Constant (training rate)",
                    "baseline": "XY baseline",
                    "baseline_no_labels": "XY baseline without SkillCorner labels",
                },
            )
        )
    )
    intercept, slope = calibration_values
    add(
        "\nLower is better for log loss and Brier score. A negative difference means the model "
        "beats the constant prediction. "
        f"Calibration of the XY baseline on the test set: intercept {intercept:+.2f}, "
        f"slope {slope:.2f} (1 is ideal).\n"
    )
    add("Per pose match:\n")
    add(_md_table(per_match))
    add("")

    add("### 1.5 Leave-one-match-out on the training matches\n")
    better = int((lomo["log_loss"] < lomo["log_loss_constant"]).sum())
    summary = pd.DataFrame(
        {
            "Metric": ["Log loss", "Log loss of the constant", "ROC AUC", "Brier score"],
            "Mean": [lomo[c].mean() for c in ("log_loss", "log_loss_constant", "auc", "brier")],
            "SD over matches": [
                lomo[c].std() for c in ("log_loss", "log_loss_constant", "auc", "brier")
            ],
            "Min": [lomo[c].min() for c in ("log_loss", "log_loss_constant", "auc", "brier")],
            "Max": [lomo[c].max() for c in ("log_loss", "log_loss_constant", "auc", "brier")],
        }
    )
    add(_md_table(summary, default=4))
    add(
        f"\nThe model beats the constant prediction on log loss in {better} of {len(lomo)} "
        "held-out matches. The penalty is the one chosen in 1.3, not re-tuned per fold.\n"
    )
    detail = lomo[["match_id", "n", "events", "log_loss", "log_loss_constant", "auc"]].copy()
    detail.columns = ["Held-out match", "Engagements", "Events", "Log loss", "Constant", "ROC AUC"]
    add(_md_table(detail.astype({"Held-out match": str}), default=4))
    add("")

    add("### 1.6 Largest coefficients of the frozen baseline\n")
    add(_md_table(coefficients))
    add(
        "\nNumeric features are standardised, so a coefficient is the change in log odds per "
        "standard deviation. Categorical features are one-hot levels. With an L2 penalty and "
        "correlated features the coefficients describe the model, not causal effects."
    )
    return "\n".join(lines)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/BASELINE.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help="update docs/BASELINE.md")
    args = parser.parse_args(argv)

    train_all, test_all = load_tables()
    train, train_flow = inclusion_flow(train_all, with_pose=False)
    test, test_flow = inclusion_flow(test_all, with_pose=True)

    model, tuning = tune_and_fit(train, PRIMARY_OUTCOME)
    chosen_c = float(tuning.loc[tuning["chosen"], "C"].iloc[0])
    model_no_labels, _ = tune_and_fit(train, PRIMARY_OUTCOME, categorical=NO_LABELS)

    y = test[PRIMARY_OUTCOME].to_numpy(dtype=float)
    predictions = {
        "constant": np.full(len(test), train[PRIMARY_OUTCOME].mean()),
        "baseline": predict_probability(model, test),
        "baseline_no_labels": predict_probability(model_no_labels, test, categorical=NO_LABELS),
    }
    weights = cluster_bootstrap_weights(
        test["cluster"].to_numpy(), test["match_id"].to_numpy(), N_BOOTSTRAP, seed=0
    )
    result = bootstrap_metrics(y, predictions, weights, reference="constant")

    per_match_rows = []
    for match_id, group in test.groupby("match_id"):
        index = group.index.to_numpy()
        part = bootstrap_metrics(
            y[index],
            {name: p[index] for name, p in predictions.items() if name != "baseline_no_labels"},
            cluster_bootstrap_weights(group["cluster"].to_numpy(), None, N_BOOTSTRAP, seed=0),
            reference="constant",
        )
        row = {"Match": str(match_id)}
        for metric, label in METRIC_LABELS.items():
            value = part[(part["model"] == "baseline") & (part["metric"] == metric)].iloc[0]
            row[label] = (
                f"{value['estimate']:.4f} ({value['ci_low']:.4f} to {value['ci_high']:.4f})"
            )
        difference = part[
            (part["model"] == "baseline") & (part["metric"] == "log_loss_vs_constant")
        ].iloc[0]
        row["Log loss minus constant"] = (
            f"{difference['estimate']:+.4f} ({difference['ci_low']:+.4f} to "
            f"{difference['ci_high']:+.4f})"
        )
        per_match_rows.append(row)

    lomo = leave_one_match_out(train, PRIMARY_OUTCOME, chosen_c)
    markdown = render(
        train_flow,
        test_flow,
        train,
        test,
        tuning,
        result,
        pd.DataFrame(per_match_rows),
        lomo,
        coefficient_table(model),
        calibration(y, predictions["baseline"]),
    )
    print(markdown)

    target = cache_dir() / "baseline" / "test_predictions.parquet"
    target.parent.mkdir(parents=True, exist_ok=True)
    test.assign(p_xy=predictions["baseline"], z_xy=logit(predictions["baseline"])).to_parquet(
        target, index=False
    )
    print(f"\nwrote {target}")
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
