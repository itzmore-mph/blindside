"""Descriptive: who presses from the pose blind side, who is pressed that way, and where.

Not pre-registered and purely descriptive. docs/PREREGISTRATION.md and the primary
comparison of docs/INCREMENTAL.md are not touched and not rerun, and no outcome column is
read. For the included engagements of the two pose matches the script tabulates

- pressing teams, pressers and carriers by the number of *confidently blind* presses
  (``p_blind_side_head`` above 0.8 under both bounds of the angular uncertainty),
- the same share per third and per channel of the pitch, next to the XY proxy, and
- how many possession losses a rerun of the pre-registered design would need to tell an
  assumed odds ratio from zero, scaled from the standard error of docs/INCREMENTAL.md 1.9.

Run from the repository root: ``uv run python scripts/tactical_insights.py --write-docs``.
Needs the body pose and the tracking of the two pose matches, as ``blindside reproduce`` does.
"""

from __future__ import annotations

import argparse
from math import ceil, log
from pathlib import Path

import numpy as np
import pandas as pd

from blindside.analysis.baseline import N_BOOTSTRAP, cluster_bootstrap_weights
from blindside.analysis.insights import (
    CONFIDENT_THRESHOLD,
    confident_blind,
    group_profile,
    required_events,
    standard_error_from_interval,
)
from blindside.analysis.pipeline import attach_pose, inclusion_flow, load_test_table
from blindside.data.events import load_match_metadata
from blindside.features.pose_features import BOUNDS, FOV_HALF_ANGLE_DEG, pose_feature_table
from blindside.features.xy_proxy import xy_blind_side_proxy

DOC = Path("docs/TACTICAL_INSIGHTS.md")
MARKER_START = (
    "<!-- insights:start (generated by scripts/tactical_insights.py, do not edit by hand) -->"
)
MARKER_END = "<!-- insights:end -->"
FEATURE = "p_blind_side_head"
#: Players with fewer engagements are listed by count only where they make the top rows.
TOP_ROWS = 8
#: Players need this many engagements to be ranked by share.
MIN_PLAYER_ENGAGEMENTS = 25

#: Unpenalised coefficient of ``p_blind_side_head`` per standard deviation, lower bound, with
#: its 95% interval, and the sample it comes from. Source: docs/INCREMENTAL.md section 1.9.
COEFFICIENT = (0.108, -0.175, 0.387)
SAMPLE_EVENTS = 217
SAMPLE_ENGAGEMENTS = 1875
SAMPLE_MATCHES = 2
#: Assumed odds ratios per standard deviation for the planning table. Assumptions, not results.
PLANNING_ODDS_RATIOS = (1.15, 1.25, 1.5)
PLANNING_POWERS = (0.5, 0.8)


def _md_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def _share(row: pd.Series) -> str:
    text = f"{100 * row['share']:.1f}"
    if np.isnan(row["low"]):
        return text
    return f"{text} ({100 * row['low']:.1f} to {100 * row['high']:.1f})"


def player_directory(match_ids: list[int]) -> tuple[dict[int, str], dict[int, str]]:
    """Display name per player (``short name, role, team``) and short name per team."""
    players: dict[int, str] = {}
    teams: dict[int, str] = {}
    for match_id in match_ids:
        metadata = load_match_metadata(match_id)
        for side in ("home_team", "away_team"):
            teams[int(metadata[side]["id"])] = str(metadata[side]["short_name"])
        for player in metadata["players"]:
            role = (player.get("player_role") or {}).get("acronym") or "?"
            team = teams.get(int(player["team_id"]), "?")
            players[int(player["id"])] = f"{player['short_name']} ({role}, {team})"
    return players, teams


def _profile_table(
    groups: pd.Series,
    blind: np.ndarray,
    proxy: np.ndarray,
    weights: np.ndarray,
    label: str,
    *,
    top: int | None = None,
    order: list[str] | None = None,
) -> pd.DataFrame:
    """Rows of :func:`group_profile` for the pose label, with the proxy share next to it."""
    pose = group_profile(groups, blind, weights)
    xy = group_profile(groups, proxy, weights).set_index("group")
    if order is not None:
        pose = pose.set_index("group").reindex([g for g in order if g in set(pose["group"])])
        pose = pose.reset_index()
    if top is not None:
        pose = pose.head(top)
    return pd.DataFrame(
        {
            label: pose["group"].to_numpy(),
            "Engagements": [f"{n:,}" for n in pose["n"]],
            "Confidently blind": pose["flagged"].to_numpy(),
            "Share, % (95% interval)": [_share(row) for _, row in pose.iterrows()],
            "XY proxy blind, %": [f"{100 * xy.loc[g, 'share']:.1f}" for g in pose["group"]],
        }
    )


def _by_share(groups: pd.Series, blind: np.ndarray, label: str) -> pd.DataFrame:
    """Players with enough engagements, the highest share of confidently blind presses first."""
    table = group_profile(groups, blind)
    table = table[table["n"] >= MIN_PLAYER_ENGAGEMENTS].sort_values(
        ["share", "n"], ascending=[False, False]
    )
    return pd.DataFrame(
        {
            label: table["group"].to_numpy(),
            "Engagements": table["n"].to_numpy(),
            "Confidently blind": table["flagged"].to_numpy(),
            "Share, %": [f"{100 * s:.1f}" for s in table["share"]],
        }
    ).head(TOP_ROWS)


def planning_table() -> tuple[pd.DataFrame, float]:
    """Events, engagements and matches needed per assumed odds ratio. Returns the SE too."""
    se = standard_error_from_interval(COEFFICIENT[1], COEFFICIENT[2])
    rows = []
    for odds_ratio in PLANNING_ODDS_RATIOS:
        row: dict[str, object] = {"Assumed odds ratio per SD": f"{odds_ratio:.2f}"}
        for power in PLANNING_POWERS:
            events = required_events(se, SAMPLE_EVENTS, odds_ratio, power=power)
            factor = events / SAMPLE_EVENTS
            row[f"Events, power {100 * power:.0f}%"] = f"{ceil(events):,}"
            row[f"Engagements, power {100 * power:.0f}%"] = f"{ceil(factor * SAMPLE_ENGAGEMENTS):,}"
            row[f"Matches, power {100 * power:.0f}%"] = ceil(factor * SAMPLE_MATCHES)
        rows.append(row)
    return pd.DataFrame(rows), se


def render(test: pd.DataFrame, features: dict[str, pd.DataFrame], weights: np.ndarray) -> str:
    """The generated block of docs/TACTICAL_INSIGHTS.md."""
    blind = confident_blind(features, FEATURE)
    proxy = xy_blind_side_proxy(
        test["approach_angle_heading_deg"].to_numpy(dtype=float), FOV_HALF_ANGLE_DEG
    )
    players, teams = player_directory(sorted(int(m) for m in test["match_id"].unique()))
    presser = test["presser_id"].map(players)
    carrier = test["carrier_id"].map(players)
    team = test["presser_team_id"].map(teams)
    per_bound = {
        bound: int((features[bound][FEATURE].to_numpy(dtype=float) > CONFIDENT_THRESHOLD).sum())
        for bound in BOUNDS
    }
    lines = [
        "### 2.1 Sample and label",
        "",
        f"{len(test):,} included on-ball engagements in {test['cluster'].nunique():,} pressed "
        f"possessions, the test set of docs/INCREMENTAL.md section 1.2. **Confidently blind**: "
        f"`{FEATURE}` above {CONFIDENT_THRESHOLD:g} under the lower and under the upper bound. "
        f"{int(blind.sum()):,} engagements ({100 * blind.mean():.1f}%) qualify. Under the lower "
        f"bound alone {per_bound['lower']:,} would, under the upper bound alone "
        f"{per_bound['upper']:,}: the stricter upper bound decides. The XY proxy calls "
        f"{int(proxy.sum()):,} ({100 * proxy.mean():.1f}%) blind.",
        "",
        "Intervals: cluster bootstrap over possessions, "
        f"{len(weights):,} resamples, stratified by match, percentile 95%. Groups below 50 "
        "engagements carry no interval. Shares of single players rest on a few dozen "
        "engagements from one match each. They describe these two matches, not the player.",
        "",
        "### 2.2 Pressing teams",
        "",
        _md_table(_profile_table(team, blind, proxy, weights, "Pressing team")),
        "",
        "### 2.3 Pressers",
        "",
        f"The {TOP_ROWS} pressers with the most confidently blind presses:",
        "",
        _md_table(_profile_table(presser, blind, proxy, weights, "Presser", top=TOP_ROWS)),
        "",
        f"Pressers with at least {MIN_PLAYER_ENGAGEMENTS} engagements, by share:",
        "",
        _md_table(_by_share(presser, blind, "Presser")),
        "",
        "### 2.4 Carriers",
        "",
        f"The {TOP_ROWS} carriers most often pressed confidently blind:",
        "",
        _md_table(_profile_table(carrier, blind, proxy, weights, "Carrier", top=TOP_ROWS)),
        "",
        f"Carriers with at least {MIN_PLAYER_ENGAGEMENTS} engagements, by share:",
        "",
        _md_table(_by_share(carrier, blind, "Carrier")),
        "",
        "### 2.5 Pitch zones",
        "",
        "`third_start` and `channel_start` of the engagement row. Both are direction-normalised "
        "to the pressing team: its `attacking_third` is the third in which the team in "
        "possession builds up, its `defensive_third` the one in front of its own goal.",
        "",
        _md_table(
            _profile_table(
                test["third_start"], blind, proxy, weights, "Third of the pressing team",
                order=["attacking_third", "middle_third", "defensive_third"],
            )
        ),
        "",
        _md_table(
            _profile_table(
                test["channel_start"], blind, proxy, weights, "Channel",
                order=["wide_left", "half_space_left", "center", "half_space_right", "wide_right"],
            )
        ),
        "",
        "### 2.6 Sample size for a rerun of the pre-registered design",
        "",
    ]  # fmt: skip
    planning, se = planning_table()
    estimate, low, high = COEFFICIENT
    rate = SAMPLE_EVENTS / SAMPLE_MATCHES
    lines += [
        f"Starting point (docs/INCREMENTAL.md section 1.9, exploratory): the unpenalised "
        f"coefficient of `{FEATURE}` is {estimate:+.3f} per standard deviation ({low:+.3f} to "
        f"{high:+.3f}, lower bound) with {SAMPLE_EVENTS} possession losses in "
        f"{SAMPLE_ENGAGEMENTS:,} engagements of {SAMPLE_MATCHES} matches. That interval implies "
        f"a standard error of {se:.3f} on the log odds scale.",
        "",
        "Planning approximation: the standard error shrinks with the square root of the number "
        "of events, everything else unchanged (event rate, feature distribution, correlation of "
        f"the head with the torso feature, about {rate:.0f} possession losses per match). A "
        "two-sided Wald test at the 5% level then needs",
        "",
        _md_table(planning),
        "",
        f"The odds ratios are assumptions for planning, not findings. The estimate from these "
        f"two matches is {np.exp(estimate):.2f} with an interval that includes 1, and "
        f"log(1.25) = {log(1.25):.3f} lies inside it. Power 50% is the sample at which the "
        "assumed effect would sit exactly on the significance threshold. The registered "
        "decision rule compares out-of-sample log loss, not this coefficient, so the table is "
        "an order of magnitude for a rerun, not a guarantee. Matches differ in how many on-ball "
        "engagements are on camera, which the table ignores.",
    ]
    return "\n".join(lines)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/TACTICAL_INSIGHTS.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help=f"update {DOC.as_posix()}")
    args = parser.parse_args(argv)

    test, _ = inclusion_flow(load_test_table(), with_pose=True)
    test, poses = attach_pose(test)
    features = {bound: pose_feature_table(test, poses, bound=bound) for bound in BOUNDS}
    weights = cluster_bootstrap_weights(
        test["cluster"].to_numpy(), test["match_id"].to_numpy(), N_BOOTSTRAP, seed=0
    )
    markdown = render(test, features, weights)
    print(markdown)
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
