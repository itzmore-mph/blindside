"""Bracket the angular uncertainty between a jitter lower bound and the Monte Carlo upper bound.

Reads the cached orientation tables of both pose matches (building them if needed), infers
the camera position from the projected image corners, and writes section 1 of
docs/RELIABILITY.md between two markers.

Run from the repository root: ``uv run python scripts/uncertainty_bracket.py --write-docs``.
No column of the dynamic events is read here.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from blindside.analysis.bracket import (
    CAMERA_EDGES,
    HALF_WINDOWS,
    PRIMARY_WINDOW,
    add_residuals,
    bracket_summary,
    residual_autocorrelation,
    residual_variance_factor,
)
from blindside.analysis.camera import CameraEstimate, cached_camera_estimate, read_corners
from blindside.analysis.consistency import SEGMENTS, SPEED_EDGES
from blindside.data.download import download_pose_archive
from blindside.data.manifest import pose_match_ids
from blindside.features.orientation_table import OrientationConfig, cached_orientation_table
from blindside.geometry.uncertainty import BOUND_CORRELATION

DOC = Path("docs/RELIABILITY.md")
MARKER_START = (
    "<!-- bracket:start (generated by scripts/uncertainty_bracket.py, do not edit by hand) -->"
)
MARKER_END = "<!-- bracket:end -->"
EXAMPLE_FRAMES = 3


def _md_table(frame: pd.DataFrame, decimals: dict[str, int] | None = None, default: int = 2) -> str:
    decimals = decimals or {}
    out = frame.copy()
    for column in out.columns:
        if pd.api.types.is_integer_dtype(out[column]):
            out[column] = out[column].map(lambda v: f"{v:,}")
        elif pd.api.types.is_float_dtype(out[column]):
            digits = decimals.get(column, default)
            out[column] = out[column].map(lambda v, d=digits: f"{v:.{d}f}")
    header = "| " + " | ".join(out.columns) + " |"
    rule = "|" + "---|" * len(out.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in out.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def _bracket_table(summary: pd.DataFrame, band_title: str | None = None) -> str:
    renamed = summary.rename(
        columns={
            "segment": "Segment",
            "band": band_title or "band",
            "n": "Poses",
            "lower_sd_deg (0.2 s)": "Lower bound, deg (0.2 s)",
            "lower_sd_deg (0.4 s)": "Lower bound, deg (0.4 s)",
            "upper_sd_deg": "Upper bound, deg",
            "ratio": "Lower / upper",
            "reconciling_correlation": "Reconciling correlation",
        }
    )
    return _md_table(
        renamed,
        {"Lower bound, deg (0.2 s)": 1, "Lower bound, deg (0.4 s)": 1, "Upper bound, deg": 1,
         "Reconciling correlation": 3},
    )  # fmt: skip


def render(
    table: pd.DataFrame, cameras: dict[int, CameraEstimate], examples: dict[int, pd.DataFrame]
) -> str:
    """Markdown of the generated block of docs/RELIABILITY.md section 1."""
    lines: list[str] = []
    add = lines.append
    with_residuals = add_residuals(table)
    overall = bracket_summary(with_residuals)

    add("### 1.1 Definitions\n")
    windows = ", ".join(
        f"{2 * h + 1} frames ({label}, residual variance factor {residual_variance_factor(h):.3f})"
        for label, h in HALF_WINDOWS.items()
    )
    add(
        "- **Upper bound**: median of the Monte Carlo SD under independent joint errors "
        "(`{segment}_sd_deg`, isotropic Gaussian, sigma = p90 / 2.5)."
    )
    add(
        "- **Lower bound (jitter)**: each angle is compared with a least-squares quadratic "
        "fitted to the unwrapped angle in a window centred on it. Windows: "
        f"{windows}. Only gap-free runs of one player are used."
    )
    add(
        "- **Conversion to an SD**: 1.4826 times the median absolute residual, divided by the "
        "square root of the residual variance factor. The factor is the variance that the "
        "centre residual of the fit has for white noise of unit variance. The median-based "
        "scale keeps sharp real turns from being counted as noise."
    )
    add(
        "- **Lower / upper**: every residual is divided by the residual SD that its own "
        f"Monte Carlo SD predicts, and the robust SD of these values is reported "
        f"({PRIMARY_WINDOW} window). 1 would mean that the Monte Carlo SD is white noise from "
        "frame to frame."
    )
    add(
        "- **Reconciling correlation**: `1 - (lower / upper)^2`, the correlation between the "
        "errors of the left and the right joint at which the Monte Carlo SD equals the lower "
        "bound (the `correlation` parameter of `blindside.geometry.uncertainty`)."
    )
    add(
        f"- Data: {len(table):,} poses of both full pose matches. "
        "All numbers in this block are produced by `scripts/uncertainty_bracket.py`.\n"
    )

    add("### 1.2 The bracket per segment\n")
    add(_bracket_table(overall))
    add("\nPer match:\n")
    per_match = []
    for match_id, group in with_residuals.groupby("match_id"):
        block = bracket_summary(group)
        block.insert(0, "Match", str(match_id))
        per_match.append(block)
    add(_bracket_table(pd.concat(per_match)))
    carried = pd.DataFrame(
        {
            "Segment": list(SEGMENTS),
            "Correlation used for the lower bound": [
                BOUND_CORRELATION["lower"][s] for s in SEGMENTS
            ],
            "Median `sd_low_deg`": [float(table[f"{s}_sd_low_deg"].median()) for s in SEGMENTS],
            "Median `sd_deg`": [float(table[f"{s}_sd_deg"].median()) for s in SEGMENTS],
        }
    )
    add("\nCarried forward in the orientation table:\n")
    add(_md_table(carried, {"Correlation used for the lower bound": 3}, default=1))
    add("")

    add("### 1.3 Autocorrelation of the jitter residuals\n")
    acf = residual_autocorrelation(with_residuals)
    wide = acf.pivot_table(
        index=["segment", "window"], columns="lag_frames", values="autocorrelation", sort=False
    ).reset_index()
    reference = acf.pivot_table(
        index=["segment", "window"], columns="lag_frames", values="white_noise", sort=False
    ).reset_index()
    out = wide[["segment", "window"]].copy()
    out.columns = ["Segment", "Window"]
    for lag in sorted(acf["lag_frames"].unique()):
        out[f"Lag {lag} ({lag / 25:g} s)"] = [
            f"{value:+.2f} ({ref:+.2f})"
            for value, ref in zip(wide[lag], reference[lag], strict=True)
        ]
    add(_md_table(out))
    add(
        "\nIn brackets: the autocorrelation that the fit itself induces on white noise. "
        "Residuals are clipped at five robust SDs before correlating.\n"
    )

    add("### 1.4 Camera position\n")
    rows = []
    for match_id, camera in cameras.items():
        rows.append(
            {
                "Match": str(match_id),
                "Frames checked": camera.n_frames,
                "Bottom image edge towards -y, %": 100 * camera.share_bottom_edge,
                "Near edge shorter than far edge, %": 100 * camera.share_near_edge_shorter,
                "Edges meet behind -y touchline, %": 100 * camera.share_meeting_point,
                "Meeting point x, m (IQR)": f"{camera.x:.1f} ({camera.x_iqr:.1f})",
                "Meeting point y, m (IQR)": f"{camera.y:.1f} ({camera.y_iqr:.1f})",
                "By period (x, y)": "; ".join(
                    f"{p}: ({x:.1f}, {y:.1f})" for p, (x, y) in camera.per_period_xy.items()
                ),
                "Reliable": "yes" if camera.reliable else "no",
            }
        )
    add(_md_table(pd.DataFrame(rows), default=1))
    add("\nExample frames (image corners projected on the pitch, metres):\n")
    for match_id, frame in examples.items():
        add(f"Match {match_id}:\n")
        add(_md_table(frame, default=1))
        add("")

    if all(camera.reliable for camera in cameras.values()):
        add("### 1.5 The bracket by speed band and by distance to the camera\n")
        add(_bracket_table(bracket_summary(with_residuals, "speed", SPEED_EDGES), "Speed"))
        add("")
        add(
            _bracket_table(
                bracket_summary(with_residuals, "camera_distance", CAMERA_EDGES),
                "Distance to camera point",
            )
        )
    else:
        add("### 1.5 The bracket by speed band\n")
        add(_bracket_table(bracket_summary(with_residuals, "speed", SPEED_EDGES), "Speed"))
        add(
            "\nThe camera position could not be inferred reliably, so the breakdown by distance "
            "to the camera is dropped."
        )
    return "\n".join(lines)


def _example_frames(archive: Path) -> pd.DataFrame:
    frames, _, corners = read_corners(archive, step=5000)
    picks = np.linspace(0, len(frames) - 1, EXAMPLE_FRAMES).round().astype(int)
    rows = []
    for i in picks:
        c = corners[i]
        rows.append(
            {
                "Pose frame": int(frames[i]),
                "Top left": f"({c[0]:.1f}, {c[1]:.1f})",
                "Top right": f"({c[6]:.1f}, {c[7]:.1f})",
                "Bottom left": f"({c[2]:.1f}, {c[3]:.1f})",
                "Bottom right": f"({c[4]:.1f}, {c[5]:.1f})",
                "Far edge, m": float(np.hypot(c[6] - c[0], c[7] - c[1])),
                "Near edge, m": float(np.hypot(c[4] - c[2], c[5] - c[3])),
            }
        )
    return pd.DataFrame(rows)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/RELIABILITY.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help="update docs/RELIABILITY.md")
    args = parser.parse_args(argv)

    config = OrientationConfig()
    tables, cameras, examples = [], {}, {}
    for match_id in pose_match_ids():
        archive = download_pose_archive(match_id)
        table = cached_orientation_table(archive, match_id, config)
        camera = cached_camera_estimate(archive, match_id)
        table["camera_distance"] = camera.distance(table["x"], table["y"]).astype(np.float32)
        tables.append(table)
        cameras[match_id] = camera
        examples[match_id] = _example_frames(archive)

    markdown = render(pd.concat(tables, ignore_index=True), cameras, examples)
    print(markdown)
    if args.write_docs:
        write_docs(markdown)
        print(f"\nupdated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
