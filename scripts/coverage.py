@dataclass(frozen=True)
class Engagement:
    """The part of an on-ball engagement that the pose pass needs."""

    event_id: str
    presser_id: int
    carrier_id: int
    frame_start: int
    period: int


def window_frames(frame_start: int, offset_s: float, period_start: int) -> list[tuple[int, bool]]:
    """Pose frames that count as "at" ``frame_start`` minus ``offset_s``.

    Parameters
    ----------
    frame_start
        Engagement start on the 10 fps tracking clock.
    offset_s
        Seconds before the engagement start.
    period_start
        First tracking frame of the period. A target before it has no window.

    Returns
    -------
    list of (pose_frame, is_nearest)
        Integer pose frames within ``HALF_WINDOW`` of the target, flagged when they are
        the one (even tracking frame) or two (odd) frames closest to it.
    """
    if frame_start - 10 * offset_s < period_start:
        return []
    target = 2.5 * frame_start - 25 * offset_s
    first = math.ceil(target - HALF_WINDOW)
    last = math.floor(target + HALF_WINDOW)
    return [(frame, abs(frame - target) <= NEAREST) for frame in range(first, last + 1)]


def _passes_gate(joints: dict[str, Any]) -> bool:
    """True if all six orientation joints exist with an error of at most ``GATE_CM``."""
    for name in ORIENTATION_JOINTS:
        joint = joints.get(name)
        if not joint:
            return False
        error = joint.get("p90_mae_cm")
        if error is None or error > GATE_CM:
            return False
    return True


class MatchCoverage:
    """Accumulates all coverage counts of one match from a stream of pose frames."""

    def __init__(self, engagements: list[Engagement], period_starts: dict[int, int]) -> None:
        self.engagements = engagements
        self.lookup: dict[int, list[tuple[int, int, bool]]] = defaultdict(list)
        for index, engagement in enumerate(engagements):
            period_start = period_starts[engagement.period]
            for offset_index, offset_s in enumerate(OFFSETS_S):
                for frame, near in window_frames(engagement.frame_start, offset_s, period_start):
                    self.lookup[frame].append((index, offset_index, near))
        shape = (len(engagements), len(OFFSETS_S))
        self.flags = {name: np.zeros(shape, dtype=bool) for name in FLAG_NAMES}
        # Sum and count of the tracking position in the nearest frame(s) at offset 0,
        # for the alignment check against the event coordinates.
        self._xy_sum = np.zeros((len(engagements), 2, 2))
        self._xy_n = np.zeros((len(engagements), 2), dtype=int)
        self.periods: dict[Any, dict[str, int]] = defaultdict(
            lambda: dict.fromkeys(PERIOD_COUNTERS, 0)
        )
        self._p90: dict[str, list[int]] = defaultdict(lambda: [0] * (P90_CAP + 1))
        self.frame_min: int | None = None
        self.frame_max: int | None = None

    def update(self, record: dict[str, Any]) -> None:
        """Consume one pose frame."""
        frame = record["frame"]
        if self.frame_min is None:
            self.frame_min = frame
        self.frame_max = frame
        players = record.get("player_data") or ()
        counts = self.periods[record.get("period")]
        counts["frames"] += 1
        counts["player_frames"] += len(players)
        n_pose = 0
        for player in players:
            detected = bool(player.get("is_detected"))
            if detected:
                counts["detected"] += 1
            joints = player.get("joints")
            if not joints:
                continue
            n_pose += 1
            if detected:
                counts["detected_with_pose"] += 1
            counts["joint_observations"] += len(joints)
            if len(joints) != len(JOINTS):
                counts["incomplete_poses"] += 1
            for name, joint in joints.items():
                error = joint.get("p90_mae_cm")
                if error is not None:
                    self._p90[name][min(int(error * 100 + 0.5), P90_CAP)] += 1
        counts["player_frames_with_pose"] += n_pose
        if n_pose:
            counts["frames_with_pose"] += 1

        wanted = self.lookup.get(frame)
        if wanted:
            self._update_engagements({p["player_id"]: p for p in players}, wanted)

    def _update_engagements(
        self, by_id: dict[int, dict[str, Any]], wanted: list[tuple[int, int, bool]]
    ) -> None:
        flags = self.flags
        for index, offset_index, near in wanted:
            engagement = self.engagements[index]
            presser = by_id.get(engagement.presser_id) or {}
            carrier = by_id.get(engagement.carrier_id) or {}
            presser_joints = presser.get("joints")
            carrier_joints = carrier.get("joints")
            cell = (index, offset_index)
            if presser_joints:
                flags["presser"][cell] = True
            if carrier_joints:
                flags["carrier"][cell] = True
            if presser_joints and carrier_joints:
                flags["both"][cell] = True
                if _passes_gate(presser_joints) and _passes_gate(carrier_joints):
                    flags["both_gated"][cell] = True
            if not near:
                continue
            if presser_joints:
                flags["presser_near"][cell] = True
            if carrier_joints:
                flags["carrier_near"][cell] = True
            if presser_joints and carrier_joints:
                flags["both_near"][cell] = True
            if offset_index == 0:
                for role, player in enumerate((presser, carrier)):
                    if player.get("x") is not None and player.get("y") is not None:
                        self._xy_sum[index, role] += (player["x"], player["y"])
                        self._xy_n[index, role] += 1

    def engagement_rows(self) -> list[dict[str, Any]]:
        """One dictionary per engagement with all flags and the pose-file positions."""
        rows = []
        for index, engagement in enumerate(self.engagements):
            row: dict[str, Any] = {"event_id": engagement.event_id}
            for name, values in self.flags.items():
                for offset_index in range(len(OFFSETS_S)):
                    row[f"{name}_{offset_index}"] = bool(values[index, offset_index])
            for role, label in enumerate(("presser", "carrier")):
                n = self._xy_n[index, role]
                xy = self._xy_sum[index, role] / n if n else (None, None)
                row[f"{label}_pose_x"] = None if xy[0] is None else float(xy[0])
                row[f"{label}_pose_y"] = None if xy[1] is None else float(xy[1])
            rows.append(row)
        return rows

    def p90_histograms(self) -> dict[str, dict[int, int]]:
        """Sparse histograms of ``p90_mae_cm`` per joint, keyed by hundredths of a cm."""
        return {
            name: {value: count for value, count in enumerate(bins) if count}
            for name, bins in self._p90.items()
        }


def hist_quantile(hist: dict[int, int], q: float) -> float:
    """Quantile in cm from a histogram keyed by hundredths of a cm (lower interpolation)."""
    total = sum(hist.values())
    if total == 0:
        return float("nan")
    threshold = q * (total - 1)
    seen = 0
    for value in sorted(hist):
        seen += hist[value]
        if seen > threshold:
            return value / 100
    return max(hist) / 100


def _git_commit(path: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(path), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return out.stdout.strip()


def run_match(match_id: int, opendata_root: Path, pose_dir: Path | None) -> dict[str, Any]:
    """Run the streaming pass for one match and return a JSON-serialisable result."""
    started = time.perf_counter()
    events = load_dynamic_events(match_id, opendata_root, columns=EVENT_COLUMNS)
    engagements_df = on_ball_engagements(events)
    metadata = load_match_metadata(match_id, opendata_root)
    period_starts = {int(p["period"]): int(p["start_frame"]) for p in metadata["match_periods"]}
    engagements = [
        Engagement(
            event_id=str(row.event_id),
            presser_id=int(row.player_id),
            carrier_id=int(row.player_in_possession_id),
            frame_start=int(row.frame_start),
            period=int(row.period),
        )
        for row in engagements_df.itertuples()
    ]

    archive = pose_archive(match_id)
    path = download_pose_archive(match_id, pose_dir)
    coverage = MatchCoverage(engagements, period_starts)
    n_frames = 0
    for record in iter_pose_frames(path):
        coverage.update(record)
        n_frames += 1
        if n_frames % 25_000 == 0:
            elapsed = time.perf_counter() - started
            print(f"{match_id}: {n_frames:,} frames, {elapsed:.0f} s", flush=True)

    flags = pd.DataFrame(coverage.engagement_rows())
    meta_cols = [c for c in EVENT_COLUMNS if c != "event_type"]
    table = engagements_df[meta_cols].astype(object).where(engagements_df[meta_cols].notna(), None)
    table = table.merge(flags, on="event_id", validate="one_to_one")
    return {
        "match_id": match_id,
        "fixture": archive.fixture,
        "archive_file": archive.file,
        "archive_sha256": archive.sha256,
        "hf_revision": load_manifest()["hf_revision"],
        "opendata_commit": _git_commit(opendata_root),
        "pitch_length": metadata["pitch_length"],
        "pitch_width": metadata["pitch_width"],
        "period_starts": period_starts,
        "n_frames": n_frames,
        "frame_min": coverage.frame_min,
        "frame_max": coverage.frame_max,
        "periods": {str(key): value for key, value in coverage.periods.items()},
        "p90_hist": {
            name: {str(k): v for k, v in hist.items()}
            for name, hist in coverage.p90_histograms().items()
        },
        "engagements": json.loads(table.to_json(orient="records")),
        "runtime_s": round(time.perf_counter() - started, 1),
    }


def _totals(result: dict[str, Any]) -> dict[str, int]:
    totals = dict.fromkeys(PERIOD_COUNTERS, 0)
    for counts in result["periods"].values():
        for name in PERIOD_COUNTERS:
            totals[name] += counts[name]
    return totals


def regression_mismatches(result: dict[str, Any]) -> list[str]:
    """Compare a result with independently published counts. Empty list means all match."""
    match_id = result["match_id"]
    problems = []
    totals = _totals(result)
    for name, expected in HF_CARD_COUNTS.get(match_id, {}).items():
        if totals[name] != expected:
            problems.append(
                f"{match_id} {name}: counted {totals[name]:,}, dataset card says {expected:,}"
            )
    expected_n = EXPECTED_ENGAGEMENTS.get(match_id)
    if expected_n is not None and len(result["engagements"]) != expected_n:
        problems.append(
            f"{match_id} engagements: found {len(result['engagements'])}, expected {expected_n}"
        )
    return problems


