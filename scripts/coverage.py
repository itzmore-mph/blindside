def _pct(part: float, whole: float) -> str:
    return "n/a" if not whole else f"{100 * part / whole:.1f}%"


def _n_pct(part: int, whole: int) -> str:
    return f"{part:,} ({_pct(part, whole)})"


def _table(header: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def engagement_table(results: list[dict[str, Any]]) -> pd.DataFrame:
    """All engagements of all matches as one table with boolean flag columns."""
    frames = []
    for result in results:
        frame = pd.DataFrame(result["engagements"])
        frame.insert(0, "match_id", result["match_id"])
        frame["pitch_length"] = result["pitch_length"]
        frames.append(frame)
    table = pd.concat(frames, ignore_index=True)
    flag_cols = [f"{name}_{i}" for name in FLAG_NAMES for i in range(len(OFFSETS_S))]
    table[flag_cols] = table[flag_cols].astype(bool)
    table["both_all_offsets"] = table[[f"both_{i}" for i in range(len(OFFSETS_S))]].all(axis=1)
    table["possession_key"] = (
        table["match_id"].astype(str) + ":" + table["associated_player_possession_event_id"]
    )
    return table


def _third_from_x(x: pd.Series, pitch_length: pd.Series) -> pd.Series:
    labels = np.where(
        x < -pitch_length / 6,
        "defensive_third",
        np.where(x > pitch_length / 6, "attacking_third", "middle_third"),
    )
    return pd.Series(labels, index=x.index)


def third_agreement(table: pd.DataFrame) -> float:
    """Share of engagements whose ``third_start`` equals the third of ``x_start`` as given."""
    derived = _third_from_x(table["x_start"].astype(float), table["pitch_length"])
    return float((derived == table["third_start"]).mean())


def alignment_checks(table: pd.DataFrame) -> dict[str, pd.Series]:
    """Compare event-side positions with the tracking positions stored in the pose file.

    Returns distances in metres between the presser's event position and the pose-file
    position at ``2.5 * frame_start``: with the event coordinates as given, and after
    mirroring rows whose ``attacking_side`` is right to left. Also the absolute difference
    between ``interplayer_distance_start`` and the presser-to-carrier distance in the pose file.
    """
    valid = table.dropna(subset=["presser_pose_x", "presser_pose_y", "x_start", "y_start"])
    x, y = valid["x_start"].astype(float), valid["y_start"].astype(float)
    pose_x, pose_y = valid["presser_pose_x"].astype(float), valid["presser_pose_y"].astype(float)
    sign = np.where(valid["attacking_side"] == "left_to_right", 1.0, -1.0)
    pair = table.dropna(
        subset=["presser_pose_x", "carrier_pose_x", "interplayer_distance_start"]
    ).astype(
        {
            "presser_pose_x": float,
            "presser_pose_y": float,
            "carrier_pose_x": float,
            "carrier_pose_y": float,
            "interplayer_distance_start": float,
        }
    )
    pose_distance = np.hypot(
        pair["presser_pose_x"] - pair["carrier_pose_x"],
        pair["presser_pose_y"] - pair["carrier_pose_y"],
    )
    return {
        "as_given": np.hypot(x - pose_x, y - pose_y),
        "mirrored": np.hypot(sign * x - pose_x, sign * y - pose_y),
        "interplayer": (pose_distance - pair["interplayer_distance_start"]).abs(),
    }


def render_report(results: list[dict[str, Any]]) -> str:
    """Markdown for docs/FEASIBILITY.md section 7."""
    results = sorted(results, key=lambda r: r["match_id"])
    table = engagement_table(results)
    n_total = len(table)
    parts: list[str] = []

    # ---- sources and definitions
    archives = "; ".join(
        f"`{r['archive_file']}` (sha256 `{r['archive_sha256'][:12]}...`)" for r in results
    )
    parts.append(
        "### 7.1 Sources and definitions\n\n"
        f"- Pose: {archives} from `huggingface.co/datasets/SkillCorner/opendata-bodypose` "
        f"at revision `{results[0]['hf_revision'][:7]}`, read in full with "
        "`blindside.data.iter_pose_frames`.\n"
        "- Engagements: `{match_id}_dynamic_events.csv` rows with "
        "`event_type == on_ball_engagement`, opendata commit "
        f"`{results[0]['opendata_commit'][:7]}`. Presser = `player_id`, "
        "carrier = `player_in_possession_id`.\n"
        "- All numbers in this section are produced by `scripts/coverage.py`.\n"
        "- **Has pose**: `joints` is not null for that player in that pose frame.\n"
        '- **Target pose frame**: `2.5 * frame_start - 25 * offset_s`. A player has pose "at" a '
        f"time if any pose frame within plus or minus {HALF_WINDOW:g} frames (0.08 s) has joints.\n"
        "- **Both**: at least one pose frame in that window in which presser and carrier have "
        "joints simultaneously. This is the definition used for the gate.\n"
        "- A target before the start of the period counts as no pose.\n"
        "- Definitions were fixed in the script before the full files were read. "
        "No outcome column was loaded."
    )

    # ---- regression and data checks
    check_lines = []
    for result in results:
        expected = HF_CARD_COUNTS.get(result["match_id"])
        totals = _totals(result)
        if expected:
            same = all(totals[name] == value for name, value in expected.items())
            check_lines.append(
                f"- Match {result['match_id']}: frames, frames with pose, player-frames, "
                "player-frames with pose and joint observations "
                + (
                    "are identical to the counts on the Hugging Face dataset card."
                    if same
                    else "**differ** from the Hugging Face dataset card."
                )
            )
        incomplete = totals["incomplete_poses"]
        check_lines.append(
            f"- Match {result['match_id']}: {totals['player_frames_with_pose']:,} poses, "
            f"{incomplete:,} of them with fewer or more than 29 joints. "
            f"Pose frames {result['frame_min']:,} to {result['frame_max']:,}. "
            f"Runtime of the pass {result['runtime_s']:.0f} s."
        )
    checks = alignment_checks(table)
    as_given, mirrored, interplayer = checks["as_given"], checks["mirrored"], checks["interplayer"]
    check_lines.append(
        "- Frame alignment and event coordinates: the presser's `x_start`, `y_start` were "
        "compared with the tracking position stored in the pose file at `2.5 * frame_start` "
        f"(n = {len(mirrored):,}). As given, {100 * (as_given <= 0.5).mean():.1f}% lie within "
        "0.5 m. After mirroring both axes for rows with `attacking_side == right_to_left`, "
        f"the median distance is {mirrored.median():.3f} m and the maximum {mirrored.max():.3f} m. "
        "Event coordinates are therefore direction-normalised (the acting team attacks "
        "towards +x), and `pose_frame = 2.5 * tracking_frame` holds on the full files."
    )
    check_lines.append(
        "- Carrier identity: `interplayer_distance_start` versus the presser-to-carrier distance "
        f"from the pose-file positions (n = {len(interplayer):,}): median absolute difference "
        f"{interplayer.median():.2f} m, 95th percentile {interplayer.quantile(0.95):.2f} m."
    )
    check_lines.append(
        f"- `third_start` equals the third of the normalised `x_start` in "
        f"{100 * third_agreement(table):.1f}% of engagements (pitch length from match.json). "
        "Thirds are therefore relative to the pressing team's own attacking direction: "
        "`defensive_third` is the presser's own third."
    )
    parts.append("### 7.2 Checks\n\n" + "\n".join(check_lines))

    # ---- player-frame coverage
    rows = []
    for result in results:
        period_keys = sorted(result["periods"], key=lambda k: (k == "None", k))
        for key in period_keys:
            c = result["periods"][key]
            rows.append(
                [
                    result["match_id"],
                    "outside periods" if key == "None" else key,
                    f"{c['frames']:,}",
                    _pct(c["frames_with_pose"], c["frames"]),
                    f"{c['player_frames']:,}",
                    f"{c['player_frames_with_pose']:,}",
                    _pct(c["player_frames_with_pose"], c["player_frames"]),
                    _pct(c["detected_with_pose"], c["detected"]),
                ]
            )
        t = _totals(result)
        rows.append(
            [
                f"**{result['match_id']}**",
                "**all**",
                f"**{t['frames']:,}**",
                f"**{_pct(t['frames_with_pose'], t['frames'])}**",
                f"**{t['player_frames']:,}**",
                f"**{t['player_frames_with_pose']:,}**",
                f"**{_pct(t['player_frames_with_pose'], t['player_frames'])}**",
                f"**{_pct(t['detected_with_pose'], t['detected'])}**",
            ]
        )
    parts.append(
        "### 7.3 Share of player-frames with joints\n\n"
        + _table(
            [
                "Match",
                "Period",
                "Frames",
                "Frames with any pose",
                "Player-frames",
                "With joints",
                "Share",
                "Share among `is_detected`",
            ],
            rows,
        )
        + "\n\nPlayer-frames count every listed player, including substitutes and players "
        "off camera. The last column restricts the denominator to `is_detected` players."
    )

    # ---- engagements at frame_start
    def summary_row(label: Any, group: pd.DataFrame, offset: int = 0) -> list[Any]:
        n = len(group)
        return [
            label,
            f"{n:,}",
            _n_pct(int(group[f"presser_{offset}"].sum()), n),
            _n_pct(int(group[f"carrier_{offset}"].sum()), n),
            _n_pct(int(group[f"both_{offset}"].sum()), n),
        ]

    header = ["", "Engagements", "Presser has pose", "Carrier has pose", "Both"]
    rows = [summary_row(mid, group) for mid, group in table.groupby("match_id")]
    rows.append([f"**{cell}**" for cell in summary_row("Total", table)])
    block = "### 7.4 Engagements with pose at `frame_start`\n\n" + _table(header, rows)

    rows = [
        summary_row(subtype, group)
        for subtype, group in sorted(table.groupby("event_subtype"), key=lambda kv: -len(kv[1]))
    ]
    block += "\n\nBy `event_subtype`, both matches pooled:\n\n" + _table(header, rows)

    order = ["defensive_third", "middle_third", "attacking_third"]
    rows = [summary_row(third, table[table["third_start"] == third]) for third in order]
    block += "\n\nBy `third_start`, both matches pooled:\n\n" + _table(header, rows)

    n_both = int(table["both_0"].sum())
    loose = int((table["presser_0"] & table["carrier_0"]).sum())
    near = int(table["both_near_0"].sum())
    gated = int(table["both_gated_0"].sum())
    block += (
        '\n\nSensitivity of the "both" count at `frame_start`, both matches pooled:\n\n'
        + _table(
            ["Definition", "Engagements"],
            [
                [
                    "Both in the same pose frame, window plus or minus 2 (gate definition)",
                    _n_pct(n_both, n_total),
                ],
                [
                    "Each somewhere in the window, not necessarily the same frame",
                    _n_pct(loose, n_total),
                ],
                ["Both in the nearest pose frame only (no window)", _n_pct(near, n_total)],
                [
                    f"Gate definition, and all six shoulder, hip and ear joints of both players "
                    f"at most {GATE_CM:g} cm",
                    _n_pct(gated, n_total),
                ],
            ],
        )
    )
    parts.append(block)

    # ---- approach
    rows = []
    for offset_index, offset_s in enumerate(OFFSETS_S):
        label = "`frame_start`" if offset_s == 0 else f"minus {offset_s:g} s"
        row = summary_row(label, table, offset_index)
        per_match = [
            _n_pct(int(group[f"both_{offset_index}"].sum()), len(group))
            for _, group in table.groupby("match_id")
        ]
        rows.append([row[0], *row[2:], *per_match])
    n_all = int(table["both_all_offsets"].sum())
    per_match_all = [
        _n_pct(int(group["both_all_offsets"].sum()), len(group))
        for _, group in table.groupby("match_id")
    ]
    rows.append(
        ["**Both at all three times**", "", "", f"**{_n_pct(n_all, n_total)}**", *per_match_all]
    )
    match_headers = [f"Both, {r['match_id']}" for r in results]
    parts.append(
        "### 7.5 Coverage during the approach\n\n"
        + _table(
            ["Time", "Presser has pose", "Carrier has pose", "Both, pooled", *match_headers], rows
        )
        + f"\n\nDenominator in every row: all {n_total:,} engagements."
    )

    # ---- joint error
    pooled: dict[str, dict[int, int]] = {}
    for result in results:
        for name, hist in result["p90_hist"].items():
            target = pooled.setdefault(name, defaultdict(int))
            for value, count in hist.items():
                target[int(value)] += count
    rows = []
    for name in ORIENTATION_JOINTS:
        per_match = [
            f"{hist_quantile({int(k): v for k, v in r['p90_hist'][name].items()}, 0.5):.1f}"
            for r in results
        ]
        rows.append(
            [
                name,
                SAMPLE_MEDIAN_CM[name],
                *per_match,
                f"{hist_quantile(pooled[name], 0.1):.1f}",
                f"{hist_quantile(pooled[name], 0.5):.1f}",
                f"{hist_quantile(pooled[name], 0.9):.1f}",
                _pct(
                    sum(c for v, c in pooled[name].items() if v > GATE_CM * 100),
                    sum(pooled[name].values()),
                ),
            ]
        )
    others = ", ".join(
        f"{name} {hist_quantile(pooled[name], 0.5):.1f}"
        for name in JOINTS
        if name not in ORIENTATION_JOINTS and name in pooled
    )
    parts.append(
        "### 7.6 `p90_mae_cm` on the full matches versus the sample\n\n"
        + _table(
            [
                "Joint",
                "Sample median (section 4)",
                *[f"Median, {r['match_id']}" for r in results],
                "10th pct, pooled",
                "Median, pooled",
                "90th pct, pooled",
                f"Share above {GATE_CM:g} cm",
            ],
            rows,
        )
        + f"\n\nValues in cm. Pooled medians of the other joints: {others}."
    )

    # ---- gate
    usable = table[table["both_0"]]
    strict = table[table["both_all_offsets"]]
    per_match_usable = ", ".join(
        f"{mid}: {int(group['both_0'].sum()):,}" for mid, group in table.groupby("match_id")
    )
    verdict = "Go" if n_both >= GATE_ENGAGEMENTS else "No-go"
    strict_verdict = "also clears" if n_all >= GATE_ENGAGEMENTS else "does not clear"
    parts.append(
        "### 7.7 Usable engagements and gate\n\n"
        f"- **Usable engagements (both players with pose at `frame_start`): {n_both:,} of "
        f"{n_total:,} ({_pct(n_both, n_total)})**, {per_match_usable}. "
        f"They belong to {usable['possession_key'].nunique():,} distinct possessions, "
        "which is the number of clusters for any bootstrap.\n"
        f"- Stricter count for the approach feature (both players with pose at `frame_start`, "
        f"minus 0.5 s and minus 1.0 s): {n_all:,} engagements in "
        f"{strict['possession_key'].nunique():,} possessions. This {strict_verdict} the gate.\n"
        f"- Gate from docs/PLAN.md: at least roughly {GATE_ENGAGEMENTS} engagements with pose "
        f"for both players across both matches. **Result: {verdict}.**"
    )
    return "\n\n".join(parts)


def replace_between_markers(text: str, block: str) -> str:
    """Replace everything between the two coverage markers with ``block``."""
    start = text.find(MARKER_START)
    end = text.find(MARKER_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("coverage markers not found in the document")
    return text[: start + len(MARKER_START)] + "\n" + block + "\n" + text[end:]


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--match", type=int, action="append", help="match id, repeatable")
    parser.add_argument("--opendata-dir", type=Path, default=None)
    parser.add_argument("--pose-dir", type=Path, default=None)
    parser.add_argument("--force", action="store_true", help="ignore cached results")
    parser.add_argument("--jobs", type=int, default=2, help="matches processed in parallel")
    parser.add_argument("--write-docs", action="store_true")
    parser.add_argument("--docs-file", type=Path, default=Path("docs/FEASIBILITY.md"))
    args = parser.parse_args(argv)

    match_ids = args.match or list(pose_match_ids())
    opendata_root = (args.opendata_dir or opendata_dir()).resolve()
    out_dir = cache_dir() / "coverage"
    out_dir.mkdir(parents=True, exist_ok=True)

    results: dict[int, dict[str, Any]] = {}
    todo = []
    for match_id in match_ids:
        cached = out_dir / f"coverage_{match_id}.json"
        if cached.exists() and not args.force:
            results[match_id] = json.loads(cached.read_text("utf-8"))
            print(f"{match_id}: using cached {cached}")
        else:
            todo.append(match_id)
    if todo:
        with ProcessPoolExecutor(max_workers=max(1, min(args.jobs, len(todo)))) as pool:
            futures = {
                match_id: pool.submit(run_match, match_id, opendata_root, args.pose_dir)
                for match_id in todo
            }
            for match_id, future in futures.items():
                result = future.result()
                (out_dir / f"coverage_{match_id}.json").write_text(json.dumps(result), "utf-8")
                results[match_id] = result
                print(f"{match_id}: done in {result['runtime_s']:.0f} s")

    ordered = [results[match_id] for match_id in match_ids]
    problems = [p for result in ordered for p in regression_mismatches(result)]
    report = render_report(ordered)
    (out_dir / "coverage_report.md").write_text(report + "\n", "utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(report)

    if problems:
        print("\nREGRESSION CHECK FAILED:\n- " + "\n- ".join(problems), file=sys.stderr)
        return 1
    if args.write_docs:
        text = args.docs_file.read_text("utf-8")
        args.docs_file.write_text(replace_between_markers(text, report), "utf-8", newline="\n")
        print(f"\nwrote section 7 block to {args.docs_file}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
