"""Phase 0 coverage count: how much body pose exists where the analysis needs it.

One streaming pass per pose match collects

1. the share of player-frames with joints, per period,
2. for every on-ball engagement, whether presser and carrier have pose at the engagement
   start and 0.5 s and 1.0 s before it,
3. the distribution of ``p90_mae_cm`` per joint.

Results are cached as JSON in ``data/cache/coverage/`` and rendered as markdown.
``--write-docs`` puts the markdown between two markers in ``docs/FEASIBILITY.md``.

Run from the repository root: ``uv run python scripts/coverage.py --write-docs``.
No outcome column of the dynamic events is read here.
"""

