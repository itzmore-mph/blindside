"""Phase 2: the reliability map of pose-derived orientation.

Reads the cached orientation tables of both pose matches (building them if needed), builds
two more per match for the sensitivity to the sigma conversion factor, and writes section 2
of docs/RELIABILITY.md between two markers together with the figures in ``docs/figures/``.

Run from the repository root: ``uv run python scripts/reliability_map.py --write-docs``.
No column of the dynamic events is read here. Match metadata is read for the pitch size only.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

from blindside.analysis.bracket import PRIMARY_WINDOW, add_residuals, bracket_summary
from blindside.analysis.camera import cached_camera_estimate
from blindside.analysis.consistency import SEGMENTS, SPEED_EDGES, USABLE_SD_DEG
from blindside.analysis.reliability import (
    GROSS_MISALIGNMENT_M,
    MIN_ZONE_POSES,
    STANDARD_PITCH,
    TOUCHLINE_EDGES,
    USABLE_THRESHOLDS,
    ZONE_BINS,
    misalignment_summary,
    pitch_zone_summary,
    standard_xy,
    touchline_distance,
    usability_sensitivity,
    usability_share,
    velocity_agreement_by_band,
)
from blindside.data.download import download_pose_archive
from blindside.data.events import load_match_metadata
from blindside.data.manifest import pose_match_ids
from blindside.features.orientation_table import (
    OrientationConfig,
    cached_orientation_table,
    orientation_cache_path,
)
from blindside.viz.reliability import (
    plot_misalignment,
    plot_reliability_composite,
    plot_usability_sensitivity,
    plot_zone_maps,
)

DOC = Path("docs/RELIABILITY.md")
FIGURES = Path("docs/figures")
COMPOSITE = FIGURES / "reliability_composite.png"
ZONES = FIGURES / "reliability_zones.png"
SENSITIVITY = FIGURES / "reliability_sensitivity.png"
MISALIGNMENT = FIGURES / "reliability_misalignment.png"
MARKER_START = (
    "<!-- reliability:start (generated by scripts/reliability_map.py, do not edit by hand) -->"
)
MARKER_END = "<!-- reliability:end -->"
SIGMA_FACTORS: tuple[float, ...] = (2.0, 2.5, 3.0)
LOWER = f"lower_sd_deg ({PRIMARY_WINDOW})"


def _md_table(frame: pd.DataFrame, decimals: dict[str, int] | None = None, default: int = 1) -> str:
    decimals = decimals or {}
    out = frame.copy()
    for column in out.columns:
        if pd.api.types.is_integer_dtype(out[column]):
            out[column] = out[column].map(lambda v: f"{v:,}")
        elif pd.api.types.is_float_dtype(out[column]):
            digits = decimals.get(column, default)
            out[column] = out[column].map(lambda v, d=digits: f"{v:.{d}f}")
    header = "| " + " | ".join(out.columns) + " |"
    rule = "|" + "---|" * len(out.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in out.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def _build_sensitivity_table(job: tuple[int, float]) -> None:
    match_id, factor = job
    config = OrientationConfig(p90_to_sigma=factor)
    archive = download_pose_archive(match_id)
    if not orientation_cache_path(archive, config).exists():
        cached_orientation_table(archive, match_id, config)


def sensitivity_tables() -> dict[float, pd.DataFrame]:
    """Upper bound SD columns of both matches for every sigma conversion factor."""
    jobs = [(match_id, factor) for match_id in pose_match_ids() for factor in SIGMA_FACTORS]
    with ProcessPoolExecutor(max_workers=4) as pool:
        list(pool.map(_build_sensitivity_table, jobs))
    columns = [f"{segment}_sd_deg" for segment in SEGMENTS]
    return {
        factor: pd.concat(
            [
                pd.read_parquet(
                    orientation_cache_path(
                        download_pose_archive(match_id), OrientationConfig(p90_to_sigma=factor)
                    ),
                    columns=columns,
                )
                for match_id in pose_match_ids()
            ],
            ignore_index=True,
        )
        for factor in SIGMA_FACTORS
    }


def _zone_range(zones: pd.DataFrame) -> pd.DataFrame:
    """Smallest, median and largest zone value per segment and statistic."""
    labels = {
        "lower_sd_deg": "Lower bound, deg",
        "upper_sd_deg": "Upper bound, deg",
        "share_usable": f"Upper bound below {USABLE_SD_DEG:g} deg, %",
    }
    rows = []
    for segment in SEGMENTS:
        selected = zones[(zones["segment"] == segment) & zones["upper_sd_deg"].notna()]
        for value, label in labels.items():
            scale = 100.0 if value == "share_usable" else 1.0
            worst = selected.loc[
                selected[value].idxmin() if value == "share_usable" else selected[value].idxmax()
            ]
            rows.append(
                {
                    "Segment": segment,
                    "Statistic": label,
                    "Zones": len(selected),
                    "Min": scale * selected[value].min(),
                    "Median": scale * selected[value].median(),
                    "Max": scale * selected[value].max(),
                    "Worst zone centre (x, y), m": f"({worst['x_centre']:.0f}, "
                    f"{worst['y_centre']:.0f})",
                }
            )
    return pd.DataFrame(rows)


def _lane_table(zones: pd.DataFrame) -> pd.DataFrame:
    """Median zone value per lane parallel to the touchline, from the camera side outwards."""
    rows = []
    for _, lane in zones.groupby("iy", sort=True):
        row: dict[str, object] = {
            "Lane centre y, m": f"{lane['y_centre'].iloc[0]:.1f}",
            "Poses": int(lane.loc[lane["segment"] == SEGMENTS[0], "n"].sum()),
        }
        for segment in SEGMENTS:
            selected = lane[lane["segment"] == segment]
            row[f"{segment}, lower"] = selected["lower_sd_deg"].median()
            row[f"{segment}, upper"] = selected["upper_sd_deg"].median()
        rows.append(row)
    return pd.DataFrame(rows)


def render(
    table: pd.DataFrame,
    with_residuals: pd.DataFrame,
    zones: pd.DataFrame,
    velocity: pd.DataFrame,
    sensitivity: pd.DataFrame,
    pitch_dims: dict[int, tuple[float, float]],
) -> str:
    """Markdown of section 2 of docs/RELIABILITY.md."""
    lines: list[str] = []
    add = lines.append

    add("### 2.1 Sources and definitions\n")
    add(
        f"- Data: {len(table):,} poses of both full pose matches, orientation tables from "
        "`blindside.features.cached_orientation_table`. All numbers in this block are produced "
        "by `scripts/reliability_map.py`. No event column is read."
    )
    add(
        "- **Upper bound**: Monte Carlo SD under independent joint errors (`{segment}_sd_deg`). "
        f"**Lower bound**: frame-to-frame jitter from the {PRIMARY_WINDOW} window (section 1.1), "
        "recomputed inside every zone or band."
    )
    dims = ", ".join(f"{m}: {d[0]:g} x {d[1]:g} m" for m, d in pitch_dims.items())
    add(
        f"- **Pitch zones**: {ZONE_BINS[0]} x {ZONE_BINS[1]} zones on a "
        f"{STANDARD_PITCH[0]:g} x {STANDARD_PITCH[1]:g} m pitch (pitch sizes from match.json: "
        f"{dims}). Positions outside the pitch count in the nearest edge zone. Zones with fewer "
        f"than {MIN_ZONE_POSES:,} poses are left out."
    )
    add(
        "- **Distance from the camera touchline**: `y` plus half the pitch width. It needs only "
        "the camera side (negative y in both matches, section 1.4), not the inferred camera point."
    )
    add(
        f"- **Usable**: angular SD below a threshold, default {USABLE_SD_DEG:g} degrees. "
        "The threshold is a convention, not a measured limit."
    )
    add(
        "- **XY to pose offset**: midpoint of lHip and rHip minus the tracking position stored in "
        "the same pose record (`centroid_dx_m`, `centroid_dy_m`).\n"
    )

    add("### 2.2 Angular uncertainty by pitch zone\n")
    add(_md_table(_zone_range(zones)))
    add("\nMedian over the zones of each lane parallel to the touchline, degrees:\n")
    add(_md_table(_lane_table(zones)))
    add(
        "\nThe camera stands behind the first lane (most negative y). "
        f"Figure: `{ZONES}`.\n\n![Angular SD by pitch zone](figures/{ZONES.name})\n"
    )

    add("### 2.3 Angular uncertainty by speed and by distance from the camera touchline\n")
    add("By player speed: section 1.5, first table. By distance from the camera touchline:\n")
    touchline = bracket_summary(with_residuals, "touchline_distance", TOUCHLINE_EDGES)
    touchline = touchline[["segment", "band", "n", LOWER, "upper_sd_deg", "ratio"]]
    touchline.columns = [
        "Segment", "Distance from camera touchline", "Poses", "Lower bound, deg",
        "Upper bound, deg", "Lower / upper",
    ]  # fmt: skip
    add(_md_table(touchline, {"Lower / upper": 2}))
    add("")

    add("### 2.4 Facing versus direction of travel by speed band\n")
    pooled = velocity[velocity["match"] == "all"]
    matches = sorted(m for m in velocity["match"].unique() if m != "all")
    out = pooled[
        ["segment", "speed_band", "n", "median_signed_deg", "median_abs_deg", "p90_abs_deg"]
    ].copy()
    out["share_above_90"] = 100.0 * pooled["share_above_90"].to_numpy()
    for match in matches:
        out[f"Median abs., {match}"] = velocity.loc[
            velocity["match"] == match, "median_abs_deg"
        ].to_numpy()
    out.columns = [
        "Segment", "Speed band", "Poses", "Median signed difference, deg",
        "Median abs. difference, deg", "90th pct, deg", "Share above 90 deg, %",
        *out.columns[7:],
    ]  # fmt: skip
    add(_md_table(out))
    add("")

    add("### 2.5 Share of usable poses\n")
    share = usability_share(table, USABLE_THRESHOLDS)
    below = [c for c in share.columns if c.startswith("below_")]
    share[below] *= 100.0
    share.columns = [
        "Segment", "Bound", "Poses", "SD median, deg",
        *[f"SD below {c.removeprefix('below_')} deg, %" for c in below],
    ]  # fmt: skip
    add(_md_table(share))
    add("\nSensitivity of the upper bound to the conversion sigma = p90 / factor:\n")
    sens = sensitivity.copy()
    sens[below] *= 100.0
    sens = sens.sort_values(
        "segment", key=lambda s: s.map({name: i for i, name in enumerate(SEGMENTS)}), kind="stable"
    )[["segment", "p90_to_sigma", "n", "sd_median_deg", *below]]
    sens.columns = [
        "Segment", "Factor", "Poses", "SD median, deg",
        *[f"SD below {c.removeprefix('below_')} deg, %" for c in below],
    ]  # fmt: skip
    add(_md_table(sens))
    add(
        "\nThe lower bound has no such sensitivity: it is anchored to the measured jitter, and a "
        "different factor changes the reconciling correlation, not the bound. "
        f"Figure: `{SENSITIVITY}`.\n\n"
        f"![Usable share by threshold and factor](figures/{SENSITIVITY.name})\n"
    )

    add("### 2.6 Offset between XY tracking and the pose centroid\n")
    offset = misalignment_summary(table)
    cm = ["median_m", "p90_m", "p99_m", "dx_median_m", "dy_median_m", "along_median_m"]
    offset[cm] *= 100.0
    offset["share_gross"] *= 100.0
    offset.columns = [
        "Speed band", "Poses", "Median, cm", "90th pct, cm", "99th pct, cm",
        f"Share above {GROSS_MISALIGNMENT_M:g} m, %", "Median along x, cm", "Median along y, cm",
        "Median along direction of travel, cm",
    ]  # fmt: skip
    add(_md_table(offset, {f"Share above {GROSS_MISALIGNMENT_M:g} m, %": 4}))
    add(
        "\nPositive along the direction of travel means that the pose centroid is ahead of the "
        f"tracking position. Figure: `{MISALIGNMENT}`.\n\n"
        f"![XY to pose offset](figures/{MISALIGNMENT.name})\n"
    )

    add("### 2.7 Composite figure\n")
    add(f"`{COMPOSITE}`, candidate for README figure 1.\n")
    add(f"![Reliability of pose-derived orientation](figures/{COMPOSITE.name})")
    return "\n".join(lines)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/RELIABILITY.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help="update docs/RELIABILITY.md")
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args(argv)

    tables, pitch_dims, sides = [], {}, set()
    for match_id in pose_match_ids():
        archive = download_pose_archive(match_id)
        table = cached_orientation_table(archive, match_id, OrientationConfig())
        metadata = load_match_metadata(match_id)
        pitch_dims[match_id] = (float(metadata["pitch_length"]), float(metadata["pitch_width"]))
        camera = cached_camera_estimate(archive, match_id)
        if not camera.reliable:
            raise SystemExit(f"camera side of match {match_id} could not be inferred reliably")
        sides.add(camera.side)
        table["touchline_distance"] = touchline_distance(
            table["y"].to_numpy(), pitch_dims[match_id][1], camera.side
        ).astype(np.float32)
        tables.append(table)
    if len(sides) != 1:
        raise SystemExit("the camera side differs between matches, zones cannot be pooled as is")
    camera_side = sides.pop()

    table = pd.concat(tables, ignore_index=True)
    del tables
    with_residuals = add_residuals(table)
    x, y = standard_xy(with_residuals, pitch_dims)
    zones = pitch_zone_summary(with_residuals, x, y)
    velocity = velocity_agreement_by_band(table)
    sensitivity = usability_sensitivity(sensitivity_tables(), USABLE_THRESHOLDS)

    markdown = render(table, with_residuals, zones, velocity, sensitivity, pitch_dims)
    print(markdown)

    if not args.no_figures:
        FIGURES.mkdir(parents=True, exist_ok=True)
        figures = {
            COMPOSITE: plot_reliability_composite(
                bracket_summary(with_residuals, "speed", SPEED_EDGES),
                zones,
                velocity,
                camera_side=camera_side,
                caption=(
                    f"Reliability of pose-derived orientation, {len(table):,} poses from "
                    f"{table['match_id'].nunique()} matches. No ground truth exists: "
                    "the true angular error lies between the two bounds."
                ),
            ),
            ZONES: plot_zone_maps(zones, camera_side),
            SENSITIVITY: plot_usability_sensitivity(sensitivity),
            MISALIGNMENT: plot_misalignment(table),
        }
        for path, figure in figures.items():
            figure.savefig(path, dpi=150)
            print(f"wrote {path}")
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
