def _comparison_table(rows: pd.DataFrame, first: list[str]) -> str:
    shown = pd.DataFrame(
        {
            **{name.capitalize(): rows[name] for name in first},
            "Bound": rows["bound"],
            "Engagements": rows["n"].map("{:,}".format),
            "Events": rows["events"].map("{:,}".format),
            "Log loss Model 0": rows["loss0"].map("{:.4f}".format),
            "Log loss Model 1": rows["loss1"].map("{:.4f}".format),
            "Model 0 minus Model 1 (95% interval)": [
                _interval(r["gain"], r["low"], r["high"]) for _, r in rows.iterrows()
            ],
        }
    )
    return _md_table(shown)


def _bin_markdown(table: pd.DataFrame, percent: bool = True, with_expected: bool = True) -> str:
    scale, digits = (100.0, 1) if percent else (1.0, 4)

    def cell(value: float, low: float, high: float, signed: bool = False) -> str:
        if np.isnan(value):
            return ""
        sign = "+" if signed else ""
        text = f"{scale * value:{sign}.{digits}f}"
        if np.isnan(low):
            return text
        return f"{text} ({scale * low:{sign}.{digits}f} to {scale * high:{sign}.{digits}f})"

    unit = ", %" if percent else ""
    shown = {
        "Bin": table["bin"],
        "Engagements": table["n"].map("{:,}".format),
    }
    if percent:
        shown["Events"] = table["events"].map("{:.0f}".format)
    shown[f"Observed{unit} (95% interval)"] = [
        cell(r["rate"], r["rate_low"], r["rate_high"]) for _, r in table.iterrows()
    ]
    if with_expected:
        shown[f"Expected under Model 0{unit}"] = [
            "" if np.isnan(v) else f"{scale * v:.{digits}f}" for v in table["expected"]
        ]
        shown[f"Observed minus expected{unit.replace('%', 'points')} (95% interval)"] = [
            cell(r["excess"], r["excess_low"], r["excess_high"], signed=True)
            for _, r in table.iterrows()
        ]
    return _md_table(pd.DataFrame(shown))


def render(test: pd.DataFrame, flow: pd.DataFrame, results: dict[str, object]) -> str:
    """Markdown of the generated block of docs/INCREMENTAL.md."""
    lines: list[str] = []
    add = lines.append
    features: dict[str, pd.DataFrame] = results["features"]  # type: ignore[assignment]
    n, events = results["n"], results["events"]

    add("### 1.1 Sources and definitions\n")
    add(
        "- Design: docs/PREREGISTRATION.md, sections 3 to 11 and the additions of 11 November 2026 "
        "in section 12. All numbers in this block are produced by `scripts/incremental_value.py`."
    )
    add(
        "- Outcome: possession loss of the pressed possession. Baseline logit `z_xy`: the frozen "
        "XY baseline of docs/BASELINE.md, refitted here and checked against the Phase 3 cache."
    )
    add(
        f"- Pose features: {', '.join(f'`{name}`' for name in POSE_FEATURES)} "
        f"(`blindside.features.pose_features`), field of view half-angle {FOV_HALF_ANGLE_DEG:g} "
        f"degrees, {DEFAULT_N_SAMPLES} Monte Carlo draws, sigma = p90 / {P90_TO_SIGMA:g}, seed 0."
    )
    add(
        "- Bounds: `lower` uses the left/right error correlation at which the Monte Carlo SD "
        "equals the frame-to-frame jitter, `upper` is independence (docs/RELIABILITY.md section 1)."
    )
    add(
        f"- Models: Model 0 = outcome on `z_xy`. Model 1 = Model 0 plus the four pose features, "
        f"L2 penalty on the pose coefficients only, chosen inside each training fold "
        f"({INNER_FOLDS}-fold, grouped by possession)."
    )
    add(
        f"- Out-of-fold predictions: grouped {N_FOLDS}-fold cross-validation, groups = "
        f"possessions, stratified by match, {N_REPEATS} repeats, predictions averaged."
    )
    add(
        f"- Intervals: paired cluster bootstrap over possessions, {N_BOOTSTRAP:,} resamples, "
        "stratified by match, percentile 95%, on the fixed out-of-fold predictions. They cover the "
        "sampling of possessions, not the variability of refitting.\n"
    )

    add("### 1.2 Sample and pose frames\n")
    add(_md_table(flow.assign(**{c: flow[c].map("{:,}".format) for c in flow.columns[1:]})))
    offset = test["pose_frame"].to_numpy() - 2.5 * test["frame_start"].to_numpy()
    add(
        f"\n{n:,} engagements with {events:,} possession losses ({100 * events / n:.1f}%). The "
        f"pre-registered minimum of {MINIMUM_EVENTS} events is "
        f"{'met' if events >= MINIMUM_EVENTS else 'NOT met'}. "
        f"Pose frame relative to t0: exactly at t0 in {100 * np.mean(offset == 0):.1f}% of "
        "engagements, half a pose frame (0.02 s) before it in "
        f"{100 * np.mean(offset == -0.5):.1f}%, further away in "
        f"{100 * np.mean(np.abs(offset) > 0.5):.1f}%, after t0 in "
        f"{100 * np.mean(offset > 0):.1f}%.\n"
    )
    add(
        "Poses flagged for swapped left and right labels (`{segment}_flip`). The angles are used "
        "as they are, no pose is corrected and no engagement is excluded:\n"
    )
    flip_rows = []
    for player, segment in (
        ("carrier", "head"),
        ("carrier", "torso"),
        ("presser", "hips"),
    ):
        flagged = test[f"{player}_{segment}_flip"].to_numpy(dtype=bool)
        flip_rows.append(
            {
                "Pose": f"{player.capitalize()} {segment}",
                "Used in": {
                    "head": "`p_blind_side_head`",
                    "torso": "`p_blind_side_torso`, `carrier_openness`",
                    "hips": "`presser_alignment`",
                }[segment],
                "Flagged": f"{int(flagged.sum()):,}",
                "Share, %": f"{100 * flagged.mean():.1f}",
            }
        )
    add(_md_table(pd.DataFrame(flip_rows)))
    add("")

    add("### 1.3 The pose features\n")
    summary_rows = []
    for bound in BOUNDS:
        table = features[bound]
        for feature in ("p_blind_side_head", "p_blind_side_torso"):
            index = bin_index(table[feature].to_numpy())
            summary_rows.append(
                {
                    "Feature": f"`{feature}`",
                    "Bound": bound,
                    **{
                        label: f"{int((index == k).sum()):,} ({100 * np.mean(index == k):.1f}%)"
                        for k, label in enumerate(BIN_LABELS)
                    },
                    "Missing": int((index == -1).sum()),
                }
            )
    add(_md_table(pd.DataFrame(summary_rows)))
    add("")
    spread_rows = []
    for bound in BOUNDS:
        table = features[bound]
        spread_rows.append(
            {
                "Bound": bound,
                "Carrier head SD, deg": f"{table['carrier_head_sd_deg'].median():.1f}",
                "Carrier torso SD, deg": f"{table['carrier_torso_sd_deg'].median():.1f}",
                "Presser hips SD, deg": f"{table['presser_hips_sd_deg'].median():.1f}",
                "`presser_alignment`, deg": f"{table['presser_alignment'].median():.1f}",
                "`carrier_openness`": f"{table['carrier_openness'].median():.2f}",
            }
        )
    add("Medians over the included engagements:\n")
    add(_md_table(pd.DataFrame(spread_rows)))
    lower_bin = bin_index(features["lower"]["p_blind_side_head"].to_numpy())
    upper_bin = bin_index(features["upper"]["p_blind_side_head"].to_numpy())
    add(
        f"\nThe two bounds put {100 * np.mean(lower_bin == upper_bin):.1f}% of the engagements "
        "into the same bin of `p_blind_side_head`. "
        f"{results['n_usable']:,} engagements ({100 * results['n_usable'] / n:.1f}%) pass the "
        f"usability threshold of {USABLE_SD_DEG:g} degrees for all three upper-bound SDs.\n"
    )

    add("### 1.4 Primary comparison (H1)\n")
    primary_rows: pd.DataFrame = results["primary_rows"]  # type: ignore[assignment]
    add(_comparison_table(primary_rows, []))
    add(
        "\nPositive means that the pose features lower the out-of-sample log loss. "
        f"**Decision rule (section 9): {decision(primary_rows)}**\n"
    )
    metric_rows: pd.DataFrame = results["metric_rows"]  # type: ignore[assignment]
    names = {
        "log_loss": "Log loss",
        "auc": "ROC AUC",
        "brier": "Brier score",
        "calibration_slope": "Calibration slope",
    }
    shown = pd.DataFrame(
        {
            "Bound": metric_rows["bound"],
            "Metric": metric_rows["metric"].map(names),
            "Model 0": metric_rows["model0"].map("{:.4f}".format),
            "Model 1": metric_rows["model1"].map("{:.4f}".format),
            "Model 0 minus Model 1 (95% interval)": [
                "" if np.isnan(r["difference"]) else _interval(r["difference"], r["low"], r["high"])
                for _, r in metric_rows.iterrows()
            ],
        }
    )
    add(_md_table(shown))
    add(
        "\nFor log loss and Brier score a positive difference favours Model 1, for ROC AUC a "
        "negative one. A calibration slope of 1 is ideal.\n"
    )
    chosen = ", ".join(
        f"{row['bound']} {row['median_c']:.3g}" for _, row in primary_rows.iterrows()
    )
    add(
        f"Median `C` chosen for the pose coefficients over the {N_FOLDS * N_REPEATS} training "
        f"folds: {chosen}. A small `C` means strong shrinkage: the inner cross-validation "
        "prefers pose coefficients near zero.\n"
    )

    add("### 1.5 Model 1 coefficients on all included engagements\n")
    coefficient_rows = []
    for bound in BOUNDS:
        table, c = results["coefficients"][bound]  # type: ignore[index]
        for _, row in table.iterrows():
            coefficient_rows.append(
                {
                    "Bound": bound,
                    "Term": f"`{row['feature']}`",
                    "Coefficient (95% interval)": _interval(
                        row["coefficient"], row["ci_low"], row["ci_high"], 3
                    ),
                    "C": f"{c:.3g}",
                }
            )
    add(_md_table(pd.DataFrame(coefficient_rows)))
    add(
        "\nDescriptive. Pose features are standardised, so a coefficient is the change in log "
        "odds per standard deviation, after shrinkage with the `C` shown. Intervals: cluster "
        "bootstrap with `C` held fixed. The test of the increment is 1.4, not this table.\n"
    )

    add("### 1.6 Possession loss by bin of `p_blind_side` (H2)\n")
    bins: dict[tuple[str, str], pd.DataFrame] = results["bins"]  # type: ignore[assignment]
    for feature in ("p_blind_side_head", "p_blind_side_torso"):
        for bound in BOUNDS:
            add(f"`{feature}`, {bound} bound:\n")
            add(_bin_markdown(bins[(feature, bound)]))
            add("")
    add(
        "Expected under Model 0 is the mean out-of-fold prediction of the recalibrated XY "
        "baseline for the engagements of the bin. Observed minus expected is what the bin shows "
        f"beyond XY. Bins with fewer than {MIN_BIN_SIZE} engagements carry no interval.\n"
    )

    add("### 1.7 Pre-registered robustness checks\n")
    add(_comparison_table(results["checks"], ["check", "variant"]))  # type: ignore[arg-type]
    add(
        "\nChecks 6 and 10 split the out-of-fold predictions of the primary comparison. "
        "All other checks refit both models. Log loss of the baselines on the test set before "
        "recalibration: "
        + ", ".join(
            f"{row['baseline']} {row['log_loss']:.4f}"
            for _, row in results["baseline_scores"].iterrows()  # type: ignore[union-attr]
        )
        + ".\n"
    )

    add("### 1.8 Secondary outcomes\n")
    add(_comparison_table(results["secondary"], ["check"]).replace("| Check |", "| Outcome |"))  # type: ignore[arg-type]
    add("")
    secondary_bins: dict[tuple[str, str], pd.DataFrame] = results["secondary_bins"]  # type: ignore[assignment]
    for outcome, label in SECONDARY_BINARY.items():
        for bound in BOUNDS:
            add(f"{label} by bin of `p_blind_side_head`, {bound} bound:\n")
            add(_bin_markdown(secondary_bins[(outcome, bound)]))
            add("")
    for bound in BOUNDS:
        add(f"Mean `possession_epv_total` by bin of `p_blind_side_head`, {bound} bound:\n")
        add(
            _bin_markdown(
                secondary_bins[("possession_epv_total", bound)], percent=False, with_expected=False
            )
        )
        add("")
    add(
        "Each binary secondary outcome has its own XY baseline fitted on the 18 training matches. "
        "No model was registered for `possession_epv_total`.\n"
    )

    add("### 1.9 Exploratory, not pre-registered\n")
    add(
        "Blind bin minus in-view bin, in percentage points of possession loss. The bins are the "
        "pre-registered ones, the contrast and its interval were not registered:\n"
    )
    contrast_rows = []
    for item in results["contrasts"]:  # type: ignore[union-attr]
        contrast_rows.append(
            {
                "Feature": f"`{item['feature']}`",
                "Bound": item["bound"],
                "Blind": f"{item['n_blind']:,}",
                "In view": f"{item['n_view']:,}",
                "Difference in observed rate, points (95% interval)": _interval(
                    *(100 * np.array(item["rate"])), 1
                ),
                "Difference in observed minus expected, points (95% interval)": _interval(
                    *(100 * np.array(item["excess"])), 1
                ),
            }
        )
    add(_md_table(pd.DataFrame(contrast_rows)))
    heading = test["approach_angle_heading_deg"].to_numpy(dtype=float)
    correlation_rows = []
    for bound in BOUNDS:
        table = features[bound]
        row = {"Bound": bound}
        for name, other in (
            ("`approach_angle_heading_deg`", heading),
            ("`z_xy`", np.asarray(results["z"], dtype=float)),
        ):
            for feature in ("p_blind_side_head", "p_blind_side_torso"):
                keep = np.isfinite(other) & table[feature].notna().to_numpy()
                rho = pd.Series(table[feature].to_numpy()[keep]).corr(
                    pd.Series(other[keep]), method="spearman"
                )
                row[f"`{feature}` with {name}"] = f"{rho:+.2f}"
        correlation_rows.append(row)
    add(
        "\nSpearman correlation of `p_blind_side` with the baseline's XY stand-in for "
        '"from behind" (angle between the carrier\'s direction of travel and the direction to the '
        "presser) and with the baseline logit:\n"
    )
    add(_md_table(pd.DataFrame(correlation_rows)))
    add(
        "\nModel 1 without a penalty on the pose coefficients (the registered Model 1 chooses "
        "the penalty by cross-validation and shrinks them to almost zero, see 1.4 and 1.5). "
        "Same folds and bootstrap as the primary comparison:\n"
    )
    add(_comparison_table(results["unpenalised_rows"], []))  # type: ignore[arg-type]
    add("\nIts coefficients on all included engagements, per standard deviation of the feature:\n")
    free_rows = []
    for name in POSE_FEATURES:
        row = {"Feature": f"`{name}`"}
        for bound in BOUNDS:
            table = results["unpenalised_coefficients"][bound].set_index("feature")  # type: ignore[index]
            row[f"{bound} bound (95% interval)"] = _interval(
                table.loc[name, "coefficient"],
                table.loc[name, "ci_low"],
                table.loc[name, "ci_high"],
                3,
            )
        free_rows.append(row)
    add(_md_table(pd.DataFrame(free_rows)))

    add("\n### 1.10 Exploratory, not pre-registered: XY proxy against the pose blind-side label\n")
    add(
        "How well does XY tracking alone reproduce the pose-based blind-side label? "
        "No outcome column is used in this section.\n"
    )
    add(
        f"- XY proxy: blind if `approach_angle_heading_deg` exceeds {FOV_HALF_ANGLE_DEG:g} "
        "degrees, the angle between the carrier's direction of travel over the 0.5 s before t0 "
        "and the direction to the presser. Same threshold as the field of view half-angle."
    )
    add(
        f"- Pose label, rows by speed and the row `{ALL_ROW}`: blind if `p_blind_side` exceeds "
        f"{LABEL_THRESHOLD:g}, on every included engagement. Row `{CONFIDENT_ROW}`: the "
        "pre-registered bins, blind above 0.9 against in view below 0.1, without the engagements "
        "between."
    )
    add(
        "- Agreement: share of engagements with the same label. Kappa: Cohen's kappa, agreement "
        "beyond what the two blind rates give by chance. Recall: share of the pose-blind "
        "engagements that the proxy also calls blind. Precision: share of the proxy-blind "
        "engagements that the pose label also calls blind."
    )
    add(
        "- Carrier speed: `carrier_speed`, mean over the 0.5 s before t0, in the bands of "
        "`blindside.analysis.consistency.SPEED_EDGES`. Intervals: cluster bootstrap over "
        "possessions as in 1.1, every "
        f"statistic recomputed per resample. Rows with fewer than {MIN_BIN_SIZE} engagements "
        "carry no interval.\n"
    )
    agreement: pd.DataFrame = results["proxy_agreement"]  # type: ignore[assignment]

    def share(row: pd.Series, name: str) -> str:
        if np.isnan(row[name]):
            return "n/a"
        if np.isnan(row[f"{name}_low"]):
            return f"{100 * row[name]:.1f}"
        return (
            f"{100 * row[name]:.1f} ({100 * row[f'{name}_low']:.1f} to "
            f"{100 * row[f'{name}_high']:.1f})"
        )

    for feature in BLIND_FEATURES:
        add(f"`{feature}`:\n")
        rows = []
        for row in agreement[agreement["feature"] == feature].to_dict("records"):
            kappa = (
                "n/a"
                if np.isnan(row["kappa"])
                else _interval(row["kappa"], row["kappa_low"], row["kappa_high"], 2)
            )
            rows.append(
                {
                    "Bound": row["bound"],
                    "Carrier speed": row["group"],
                    "Engagements": f"{row['n']:,}",
                    "Pose blind, %": f"{100 * row['pose_blind']:.1f}",
                    "Proxy blind, %": f"{100 * row['xy_blind']:.1f}",
                    "Agreement, % (95% interval)": share(row, "agreement"),
                    "Kappa (95% interval)": kappa,
                    "Recall, % (95% interval)": share(row, "recall"),
                    "Precision, % (95% interval)": share(row, "precision"),
                }
            )
        add(_md_table(pd.DataFrame(rows)) + "\n")
    return "\n".join(lines).rstrip("\n")


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/INCREMENTAL.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write-docs", action="store_true", help="update docs/INCREMENTAL.md")
    args = parser.parse_args(argv)

    train_all, test_all = load_tables()
    train, _ = inclusion_flow(train_all, with_pose=False)
    test, flow = inclusion_flow(test_all, with_pose=True)
    print("engagement poses ...", flush=True)
    test, poses = attach_pose(test)
    results = compute(train, test, poses)
    markdown = render(test, flow, results)
    print(markdown)

    target = cache_dir() / "pose_features" / "engagement_features.parquet"
    target.parent.mkdir(parents=True, exist_ok=True)
    saved = test.assign(z_xy=results["z"])
    for bound in BOUNDS:
        table = results["features"][bound]  # type: ignore[index]
        saved = saved.join(table.add_suffix(f"__{bound}"))
        oof = results["primary"][bound]  # type: ignore[index]
        saved[f"p_model0__{bound}"] = oof.model0
        saved[f"p_model1__{bound}"] = oof.model1
    saved.to_parquet(target, index=False)
    print(f"\nwrote {target}")
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
