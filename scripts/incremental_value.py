def decision(rows: pd.DataFrame) -> str:
    """Wording of the pre-registered decision rule for the primary comparison."""
    above = {row["bound"]: row["low"] > 0 for _, row in rows.iterrows()}
    if all(above.values()):
        return "H1 is supported: the 95% interval lies above zero under both uncertainty bounds."
    if any(above.values()):
        bound = next(b for b, value in above.items() if value)
        return (
            f"The result depends on the error model: the 95% interval lies above zero under the "
            f"{bound} bound only."
        )
    return (
        "No detectable increment: the 95% interval of the log loss difference includes zero or "
        "lies below it under both uncertainty bounds."
    )


def _comparison_table(rows: pd.DataFrame, first: list[str]) -> str:
    shown = pd.DataFrame(
        {
            **{name.capitalize(): rows[name] for name in first},
            "Bound": rows["bound"],
            "Engagements": rows["n"].map("{:,}".format),
            "Events": rows["events"].map("{:,}".format),
            "Log loss Model 0": rows["loss0"].map("{:.4f}".format),
            "Log loss Model 1": rows["loss1"].map("{:.4f}".format),
            "Model 0 minus Model 1 (95% interval)": [
                _interval(r["gain"], r["low"], r["high"]) for _, r in rows.iterrows()
            ],
        }
    )
    return _md_table(shown)


def _bin_markdown(table: pd.DataFrame, percent: bool = True, with_expected: bool = True) -> str:
    scale, digits = (100.0, 1) if percent else (1.0, 4)

    def cell(value: float, low: float, high: float, signed: bool = False) -> str:
        if np.isnan(value):
            return ""
        sign = "+" if signed else ""
        text = f"{scale * value:{sign}.{digits}f}"
        if np.isnan(low):
            return text
        return f"{text} ({scale * low:{sign}.{digits}f} to {scale * high:{sign}.{digits}f})"

    unit = ", %" if percent else ""
    shown = {
        "Bin": table["bin"],
        "Engagements": table["n"].map("{:,}".format),
    }
    if percent:
        shown["Events"] = table["events"].map("{:.0f}".format)
    shown[f"Observed{unit} (95% interval)"] = [
        cell(r["rate"], r["rate_low"], r["rate_high"]) for _, r in table.iterrows()
    ]
    if with_expected:
        shown[f"Expected under Model 0{unit}"] = [
            "" if np.isnan(v) else f"{scale * v:.{digits}f}" for v in table["expected"]
        ]
        shown[f"Observed minus expected{unit.replace('%', 'points')} (95% interval)"] = [
            cell(r["excess"], r["excess_low"], r["excess_high"], signed=True)
            for _, r in table.iterrows()
        ]
    return _md_table(pd.DataFrame(shown))


def render(test: pd.DataFrame, flow: pd.DataFrame, results: dict[str, object]) -> str:
    """Markdown of the generated block of docs/INCREMENTAL.md."""
    lines: list[str] = []
    add = lines.append
    features: dict[str, pd.DataFrame] = results["features"]  # type: ignore[assignment]
    n, events = results["n"], results["events"]

    add("### 1.1 Sources and definitions\n")
    add(
        "- Design: docs/PREREGISTRATION.md, sections 3 to 11 and the additions of 11 November 2026 "
        "in section 12. All numbers in this block are produced by `scripts/incremental_value.py`."
    )
    add(
        "- Outcome: possession loss of the pressed possession. Baseline logit `z_xy`: the frozen "
        "XY baseline of docs/BASELINE.md, refitted here and checked against the Phase 3 cache."
    )
