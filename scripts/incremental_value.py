"""Phase 4: what body pose adds to the XY baseline for the outcome of an on-ball engagement.

Runs the comparison fixed in docs/PREREGISTRATION.md: Model 0 (recalibrated XY baseline)
against Model 1 (the same plus four pose features), under the lower and the upper bound of
the angular uncertainty, with the pre-registered robustness checks, the binned description
of ``p_blind_side`` and the secondary outcomes. Everything beyond the pre-registration is
written to a section titled exploratory.

Run from the repository root: ``uv run python scripts/incremental_value.py --write-docs``.
The first run streams both pose archives once (a few minutes) and caches the engagement poses.
"""

