"""Phase 1: build the cached orientation tables and report on them.

Steps:

1. Build the orientation table of the committed sample phase and of both full pose matches
   (``data/cache/orientation/*.parquet``, git ignored). Each full match runs in its own
   process, which also gives a clean runtime and peak memory figure per match.
2. Re-measure sections 4 and 5 of docs/FEASIBILITY.md on the full matches.
3. Draw the velocity consistency figure (the Phase 1 gate) to ``docs/figures/``.

Run from the repository root: ``uv run python scripts/orientation_tables.py --write-docs``.
No column of the dynamic events is read here.
"""

from __future__ import annotations

import argparse
import json
import resource
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import pandas as pd

from blindside.analysis.consistency import (
    flip_summary,
    head_estimator_comparison,
    segment_agreement,
    temporal_jitter,
    uncertainty_summary,
    velocity_agreement,
)
from blindside.data.download import download_pose_archive
from blindside.data.manifest import pose_match_ids
from blindside.data.paths import sample_pose_path
from blindside.features.orientation_table import (
    OrientationConfig,
    cached_orientation_table,
    orientation_cache_path,
)

SAMPLE_MATCH_ID = 1925299
FIGURE = Path("docs/figures/phase1_velocity_check.png")
DOC = Path("docs/FEASIBILITY.md")
MARKER_START = (
    "<!-- orientation:start (generated by scripts/orientation_tables.py, do not edit by hand) -->"
)
MARKER_END = "<!-- orientation:end -->"
SEGMENTS = ("torso", "hips", "head")


def _peak_rss_mb() -> float:
    """Peak resident set size of this process in MB (bytes on macOS, kilobytes on Linux)."""
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / 1e6 if sys.platform == "darwin" else peak / 1e3


def _stats_path(parquet: Path) -> Path:
    return parquet.with_suffix(".build.json")


def build_match(match_id: int, refresh: bool) -> dict[str, float]:
    """Build (or load) the table of one full match and return its build statistics."""
    config = OrientationConfig()
    archive = download_pose_archive(match_id)
    parquet = orientation_cache_path(archive, config)
    stats_file = _stats_path(parquet)
    if parquet.exists() and stats_file.exists() and not refresh:
        return json.loads(stats_file.read_text())
    start = time.perf_counter()
    table = cached_orientation_table(archive, match_id, config, refresh=True)
    stats = {
        "match_id": match_id,
        "rows": len(table),
        "runtime_s": round(time.perf_counter() - start, 1),
        "peak_rss_mb": round(_peak_rss_mb()),
        "archive_mb": round(archive.stat().st_size / 1e6),
        "parquet_mb": round(parquet.stat().st_size / 1e6, 1),
    }
    stats_file.write_text(json.dumps(stats, indent=2) + "\n")
    return stats


def _md_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(frame.columns) + " |"
    rule = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def _fmt(frame: pd.DataFrame, decimals: dict[str, int]) -> pd.DataFrame:
    out = frame.copy()
    for column in out.columns:
        if column in decimals:
            out[column] = out[column].map(lambda v, d=decimals[column]: f"{v:,.{d}f}")
        elif pd.api.types.is_integer_dtype(out[column]):
            out[column] = out[column].map(lambda v: f"{v:,}")
    return out


def render(sample: pd.DataFrame, full: pd.DataFrame, stats: list[dict[str, float]]) -> str:
    """Markdown of section 9 of docs/FEASIBILITY.md."""
    config = OrientationConfig()
    lines: list[str] = []
    add = lines.append

    add("### 9.1 Sources and definitions\n")
    add(
        "- Tables: `blindside.features.build_orientation_table` on the sample phase and on both "
        "full pose archives. One row per player and pose frame with joints "
        f"({len(full):,} rows on the full matches, {len(sample):,} on the sample)."
    )
    add(
        f"- Monte Carlo: {config.n_samples} draws, isotropic Gaussian, sigma = p90 / "
        f"{config.p90_to_sigma:g}, joint correlation {config.correlation:g}, seed {config.seed}. "
        "All three are assumptions of the error model."
    )
    add(
        "- Facing angle: left-to-right joint axis rotated by +90 degrees. "
        "Torso = shoulders, hips = hips, head = ears."
    )
    add(
        f"- Velocity: central difference of the pose-file XY over plus or minus "
        f"{config.velocity_half_window} pose frames "
        f"({2 * config.velocity_half_window / 25:.1f} s window), not across period boundaries. "
        "This is the definition that reproduces the sample counts of section 5 exactly."
    )
    add("- All numbers in this section are produced by `scripts/orientation_tables.py`.\n")

    add("### 9.2 Runtime and memory\n")
    table = pd.DataFrame(stats)[
        ["match_id", "rows", "archive_mb", "runtime_s", "peak_rss_mb", "parquet_mb"]
    ]
    table.columns = ["Match", "Rows", "Archive, MB", "Runtime, s", "Peak RSS, MB", "Parquet, MB"]
    add(_md_table(_fmt(table.astype({"Match": str}), {"Parquet, MB": 1})))
    add(
        "\nOne process per match, both running at the same time, streaming straight from the zip. "
        "Peak RSS is the maximum resident set size of the process.\n"
    )

    add("### 9.3 Angular uncertainty, full matches versus sample (section 4)\n")
    blocks = []
    for label, data in (("sample", sample), ("full matches", full)):
        block = uncertainty_summary(data)
        block.insert(0, "data", label)
        blocks.append(block)
    summary = pd.concat(blocks)
    order = summary["segment"].map({name: i for i, name in enumerate(SEGMENTS)})
    summary = summary.iloc[order.argsort(kind="stable")]
    summary["share_sd_below_20"] *= 100
    summary.columns = [
        "Data", "Segment", "Poses", "Median width, m", "SD median, deg",
        "SD 90th pct, deg", "SD 99th pct, deg", "SD below 20 deg, %",
    ]  # fmt: skip
    add(
        _md_table(
            _fmt(
                summary,
                {
                    "Median width, m": 3,
                    "SD median, deg": 1,
                    "SD 90th pct, deg": 1,
                    "SD 99th pct, deg": 1,
                    "SD below 20 deg, %": 1,
                },
            )
        )
    )
    agreement = segment_agreement(full)
    add(
        "\nAgreement between segments on the full matches (median absolute difference): "
        + ", ".join(f"{a} versus {b} {value:.1f} degrees" for (a, b), value in agreement.items())
        + ".\n"
    )

    add("### 9.4 Head estimator: ear axis versus nose direction\n")
    head = head_estimator_comparison(full)
    add(_md_table(_fmt(head, {c: 1 for c in head.columns if c != "Estimator"})))
    add(
        "\nJitter is the absolute change between consecutive pose frames (0.04 s) of one player. "
        "It mixes real head movement with noise, so it is only meaningful as a comparison "
        "between two estimators on the same frames.\n"
    )

    add("### 9.5 Front/back ambiguity\n")
    flips = flip_summary(full)
    add(
        _md_table(
            _fmt(
                flips,
                {
                    c: 2 if c == "Share, %" else 1
                    for c in flips.columns[2:]
                    if not pd.api.types.is_integer_dtype(flips[c])
                },
            )
        )
    )
    add(
        "\nA pose is flagged when the facing angle from the left/right labels points more than "
        "90 degrees away from the label-independent forward cue (nose ahead of the ear midpoint, "
        "toes ahead of the heels).\n"
    )

    add("### 9.6 Velocity consistency check on the full matches (section 5)\n")
    for segment in ("hips", "torso"):
        per_match = [
            velocity_agreement(full[full["match_id"] == m], segment)
            for m in sorted(full["match_id"].unique())
        ]
        pooled = velocity_agreement(full, segment)
        out = pooled[["speed_band", "n", "median_abs_deg", "p90_abs_deg", "share_above_90"]].copy()
        out["share_above_90"] *= 100
        for match_table in per_match:
            out[f"m{len(out.columns)}"] = match_table["median_abs_deg"].to_numpy()
        out.columns = [
            "Speed band", "n", "Median abs. difference, deg", "90th pct, deg",
            "Share above 90 deg, %",
            *[f"Median, {m}" for m in sorted(full["match_id"].unique())],
        ]  # fmt: skip
        add(f"{segment.capitalize()} facing versus velocity heading, both matches pooled:\n")
        add(_md_table(_fmt(out, {c: 1 for c in out.columns if c not in ("Speed band", "n")})))
        add("")
    add("### 9.7 Frame-to-frame change versus the Monte Carlo SD\n")
    jitter = temporal_jitter(full)
    jitter.columns = [
        "Segment", "Consecutive pairs", "Change median, deg", "Change 90th pct, deg",
        "MC SD median, deg", "Change median if the error were independent per frame, deg",
    ]  # fmt: skip
    add(_md_table(_fmt(jitter, {c: 1 for c in jitter.columns[2:]})))
    add(f"\nFigure: `{FIGURE}`.")
    return "\n".join(lines)


def write_docs(markdown: str) -> None:
    """Replace the block between the two markers in docs/FEASIBILITY.md."""
    text = DOC.read_text("utf-8")
    start, end = text.index(MARKER_START), text.index(MARKER_END)
    DOC.write_text(text[: start + len(MARKER_START)] + "\n" + markdown + "\n" + text[end:], "utf-8")


def main(argv: list[str] | None = None) -> int:
    """Command line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--refresh", action="store_true", help="rebuild the cached tables")
    parser.add_argument("--write-docs", action="store_true", help="update docs/FEASIBILITY.md")
    parser.add_argument("--no-figure", action="store_true")
    args = parser.parse_args(argv)

    config = OrientationConfig()
    sample = cached_orientation_table(
        sample_pose_path(), SAMPLE_MATCH_ID, config, refresh=args.refresh
    )
    match_ids = pose_match_ids()
    with ProcessPoolExecutor(max_workers=len(match_ids)) as pool:
        stats = list(pool.map(build_match, match_ids, [args.refresh] * len(match_ids)))
    full = pd.concat(
        [
            pd.read_parquet(orientation_cache_path(download_pose_archive(m), config))
            for m in match_ids
        ],
        ignore_index=True,
    )

    markdown = render(sample, full, stats)
    print(markdown)
    if not args.no_figure:
        from blindside.viz.consistency import plot_velocity_check

        FIGURE.parent.mkdir(parents=True, exist_ok=True)
        figure = plot_velocity_check(full)
        figure.savefig(FIGURE, dpi=150)
        print(f"\nwrote {FIGURE}")
    if args.write_docs:
        write_docs(markdown)
        print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
